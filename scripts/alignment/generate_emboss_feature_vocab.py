#!/usr/bin/env python3
"""A5-8c3b (B09 F218): the DNA feature vocabulary of EMBOSS 6.6.0 as the program applies it to the features read from GenBank / EMBL entries, written as C# data
(src/Seqeron/Algorithms/Seqeron.Genomics.Infrastructure/EmbossFeatureVocabulary.g.cs).
* TAGS: the tag table of the `emboss` vocabulary (Etags.emboss -> Etags.gff3 -> Etags.embl, `featVocabReadTags`): case-insensitive name -> canonical name + value type
  (QTEXT QWORD BTEXT TEXT VOID LIMITED QLIMITED SPECIAL QSPECIAL TAGVAL); the first tag read (`note`) is the default of an unknown tag.
* TYPES: MEASURED on the installed diffseq: a GenBank entry with one feature of the type X over 1..100 is compared with a copy with one SNP, and the type the program prints for X is recorded
  (`ajFeattypeGetExternal` of the internal type; aliases, SO ids and the GFF3 names map to the EMBL names, an unknown type is `misc_feature`, `source` is not printed: `databank_entry` too).
Usage: python3 scripts/alignment/generate_emboss_feature_vocab.py OUT.g.cs      (needs EMBOSS 6.6.0 with its data files in /usr/share/EMBOSS/data)
"""
import os, random, re, subprocess, sys, tempfile

DATA = '/usr/share/EMBOSS/data/'


def read_tags():
    tags = {}
    order = []

    def read(fname):
        for raw in open(DATA + fname):
            line = ' '.join(raw.split())
            if line.startswith('#'):
                m = re.match(r'#include (\S+)', line, re.I)
                if m and not line.lower().startswith('#includeonly'):
                    read(m.group(1))
                continue
            if not line: continue
            m = re.match(r'(\S+)\s+([A-Za-z]+)\s*(.*)$', line)
            if not m: continue
            name, typ, rest = m.groups()
            if typ not in ('QTEXT', 'QWORD', 'BTEXT', 'TEXT', 'VOID', 'LIMITED', 'QLIMITED', 'SPECIAL', 'QSPECIAL', 'TAGVAL'): continue
            if name.lower() in tags: continue
            tags[name.lower()] = (name, typ)
            order.append(name)

    read('Etags.emboss')
    return tags, order


def type_names():
    names = []
    for f in ('Efeatures.embl', 'Efeatures.gff3'):
        for line in open(DATA + f):
            if not line.strip() or line.lstrip().startswith('#') or line[0] in ' \t': continue
            t = line.split()
            if t[0].startswith('/'): continue
            names.append(t[0])
            if len(t) > 1 and not t[1].startswith('#') and not t[1].startswith('='): names.append(t[1])
    extra = ['zzz_unknown', "5'UTR", "3'UTR", 'x', 'misc_feature']
    names += extra
    return list(dict.fromkeys(names))


def gb(name, seq, feats):
    o = 'LOCUS       %s %d bp    DNA     linear   UNK 01-JAN-2000\nDEFINITION  test.\nACCESSION   %s\nVERSION     %s.1\nFEATURES             Location/Qualifiers\n' % (name, len(seq), name, name)
    for ty, loc in feats:
        o += '     %-15s %s\n' % (ty, loc)
    o += 'ORIGIN\n'
    for i in range(0, len(seq), 60):
        o += '%9d %s\n' % (i + 1, ' '.join(seq[i + j:i + j + 10].lower() for j in range(0, 60, 10) if seq[i + j:i + j + 10]))
    return o + '//\n'


def measure_types(names):
    rnd = random.Random(1)
    a = ''.join(rnd.choice('ACGT') for _ in range(120))
    b = list(a); b[9] = 'A' if a[9] != 'A' else 'C'; b = ''.join(b)
    res = {}
    with tempfile.TemporaryDirectory() as d:
        open(os.path.join(d, 'b.gb'), 'w').write(gb('SEQB', b, []))
        for n in names:
            key = n.lower()
            if key in res: continue
            open(os.path.join(d, 'a.gb'), 'w').write(gb('SEQA', a, [(n, '1..100')]))
            subprocess.run(['diffseq', 'a.gb', 'b.gb', '-wordsize', '4', '-outfile', 'o.rep', '-aoutfeat', 'a.gff', '-boutfeat', 'b.gff', '-auto'], cwd=d, capture_output=True, text=True)
            out = open(os.path.join(d, 'o.rep')).read()
            feats = [l[len('Feature: '):] for l in out.split('\n') if l.startswith('Feature: ')]
            res[key] = feats[0].split(' ')[0] if feats else ''
    return res


def main(out):
    tags, order = read_tags()
    types = measure_types(type_names())
    lines = ['// <auto-generated by scripts/alignment/generate_emboss_feature_vocab.py: do not edit>', 'namespace Seqeron.Genomics.Infrastructure;', '',
             '/// <summary>The DNA feature vocabulary of EMBOSS 6.6.0 (tags of Etags.emboss, types measured on the installed program; A5-8c3b, B09 F218).</summary>',
             'internal static partial class EmbossFeatureVocabulary', '{', '    /// <summary>The first tag of the vocabulary: the tag an unknown one is stored under.</summary>', '    internal const string DefaultTag = "%s";' % order[0], '',
             '    // lower-case tag name, canonical name, value type', '    private static readonly (string Key, string Name, string Kind)[] TagData =', '    [']
    for key, (name, typ) in tags.items():
        lines.append('        ("%s", "%s", "%s"),' % (key, name, typ))
    lines += ['    ];', '', '    // lower-case feature key as it is written in the entry, the type the program prints ("" = not printed: source)', '    private static readonly (string Key, string Type)[] TypeData =', '    [']
    for key, t in sorted(types.items()):
        lines.append('        ("%s", "%s"),' % (key.replace('\\', '\\\\').replace('"', '\\"'), t.replace('\\', '\\\\').replace('"', '\\"')))
    lines += ['    ];', '', '    /// <summary>The type printed for an unknown feature key.</summary>', '    internal const string DefaultType = "%s";' % types['zzz_unknown'], '}', '']
    open(out, 'w').write('\n'.join(lines))
    print(len(tags), 'tags', len(types), 'types', 'default type', types['zzz_unknown'], 'default tag', order[0])


if __name__ == '__main__':
    main(sys.argv[1])
