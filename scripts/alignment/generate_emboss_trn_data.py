#!/usr/bin/env python3
"""B09 WP61: the genetic code files EGC.* of EMBOSS 6.6.0 (emboss-data 6.6.0: share/EMBOSS/data) embedded as the C# table
src/Seqeron/Algorithms/Seqeron.Genomics.Infrastructure/EmbossTrnData.g.cs (the comment lines are dropped, as ajtrn.c's trnNoComment does; EGC.index is kept whole).
Usage: python3 scripts/alignment/generate_emboss_trn_data.py [/usr/share/EMBOSS/data] > src/.../EmbossTrnData.g.cs"""
import os, re, sys

D = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/EMBOSS/data'


def main():
    files = sorted((f for f in os.listdir(D) if re.fullmatch(r'EGC\.\d+', f)), key=lambda f: int(f[4:]))
    print('// <auto-generated by scripts/alignment/generate_emboss_trn_data.py: do not edit>')
    print('namespace Seqeron.Genomics.Infrastructure;')
    print()
    print('/// <summary>The genetic code files <c>EGC.n</c> and <c>EGC.index</c> of EMBOSS 6.6.0 (B09 WP61, F280), embedded (comment lines dropped).</summary>')
    print('internal sealed partial class EmbossTrn')
    print('{')
    print('    private static readonly (int Table, string Text)[] DataFiles =')
    print('    [')
    for f in files:
        text = ''.join(l for l in open(os.path.join(D, f), encoding='latin-1', newline='') if not l.lstrip().startswith('#'))
        assert '"""' not in text
        print('        (%d, """' % int(f[4:]))
        print(text.rstrip('\n'))
        print('"""),')
    print('    ];')
    print()
    idx = open(os.path.join(D, 'EGC.index'), encoding='latin-1', newline='').read()
    print('    private const string IndexText = """')
    print(idx.rstrip('\n'))
    print('""";')
    print('}')


if __name__ == '__main__':
    main()
