#!/usr/bin/env python3
"""Transcribes every substitution matrix of T-Coffee 13.41 `matrices.h` (Debian t-coffee 13.45.0.4846264+really13.41.0.28bdc39+dfsg-1, sources.debian.org
`t_coffee_source/t_coffee_lib/matrices.h`) that `read_matrice` (io_func.c) can return into src/.../SequenceAligner.TCoffeeMatrixTables.cs.
usage: generate_tcoffee_matrix_tables.py matrices.h OUT.cs
Every array has 276 values (the triangle over the 23 letters "abcdefghiklmnpqrstvwxyz"). Names read_matrice maps: pam -> pam250mt, blosum -> blosum62mt,
id / ID / idmat -> idmat, dna_idmat -> the array idmat, exon2mt -> blosum62mt."""
import re, sys
src = open(sys.argv[1]).read()
arrays = {}
for m in re.finditer(r'int\s+(\w+)\s*\[\s*\]\s*=\s*\{(.*?)\};', src, re.S):
    vals = [int(x) for x in re.findall(r'-?\d+', re.sub(r'/\*.*?\*/', '', m.group(2), flags=re.S))]
    if len(vals) == 276: arrays[m.group(1)] = vals
out = ['// <auto-generated> by scripts/alignment/generate_tcoffee_matrix_tables.py from T-Coffee 13.41 matrices.h; do not edit. </auto-generated>', '#nullable enable',
       'namespace Seqeron.Genomics.Alignment;', '',
       '/// <summary>All 23-letter triangular matrices of T-Coffee 13.41 <c>matrices.h</c> that <c>read_matrice</c> can return, by name.</summary>',
       'internal static class TcMatrixCatalog', '{',
       '    private static readonly Dictionary<string, int[]> Arrays = new(StringComparer.Ordinal)', '    {']
for name, vals in arrays.items():
    out.append(f'        ["{name}"] = new[]')
    out.append('        {')
    for i in range(0, 276, 23): out.append('            ' + ', '.join(map(str, vals[i:i + 23])) + ',')
    out.append('        },')
out += ['    };', '',
        '    /// <summary>The matrix vector <c>read_matrice(name)</c> selects, or <c>null</c> for a name it does not know as a header matrix.</summary>',
        '    public static int[]? Find(string name)',
        '    {',
        '        string n = name switch',
        '        {',
        '            "pam" or "PAM" => "pam250mt",',
        '            "blosum" or "BLOSUM" => "blosum62mt",',
        '            "id" or "ID" or "idmat" => "idmat",',
        '            "dna_idmat" => "idmat",',
        '            "exon2mt" => "blosum62mt",',
        '            _ => name,',
        '        };',
        '        return Arrays.TryGetValue(n, out var v) ? v : null;',
        '    }', '}', '']
open(sys.argv[2], 'w').write('\n'.join(out))
