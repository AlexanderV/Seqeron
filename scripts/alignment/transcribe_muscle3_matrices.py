#!/usr/bin/env python3
"""Transcribes the score matrices of MUSCLE 3.8.1551 (Debian muscle3 3.8.1551-2: vtml2.cpp VTML_LA / VTML_SP, mpam200.cpp PAM200, nucmx.cpp NUC_SP) and the Dayhoff table of
msadistkimura.cpp into src/Seqeron/Algorithms/Seqeron.Genomics.Alignment/SequenceAligner.MuscleMatrices.cs (the tables as double literals; the loader applies the C++ casts /
centers: VTML_LA (float) x; PAM200 (float) x + 20; VTML_SP (float) (x + 22); NUC_SP (float) x + 60).

Usage: python3 -I transcribe_muscle3_matrices.py SRC_DIR OUT.cs      (SRC_DIR = the directory fetched by docs/Validation/review-2026-09/handoff/A1-10c-muscle/fetch_src.py)
The Dayhoff table is embedded in SequenceAligner.Muscle.cs (DayhoffPams); `--dayhoff SRC_DIR` prints it.
"""
import re, sys, os


def rows(text, name):
    body = re.search(r'float\s+' + name + r'\[32\]\[32\]\s*=\s*\{(.*?)\n\s*\};', text, re.S).group(1)
    body = re.sub(r'//[^\n]*', '', body)
    return [[x.strip() for x in r.group(1).replace('\n', ' ').split(',')] for r in re.finditer(r'(?:ROW|RNC)\s*\(([^)]*)\)', body)]


def main(src, out_path):
    rd = lambda f: open(os.path.join(src, f)).read()
    la, sp = rows(rd('vtml2.cpp'), 'VTML_LA'), rows(rd('vtml2.cpp'), 'VTML_SP')
    pam, nuc = rows(rd('mpam200.cpp'), 'PAM200'), rows(rd('nucmx.cpp'), 'NUC_SP')
    assert (len(la), len(sp), len(pam), len(nuc)) == (20, 21, 20, 4)
    out = ['// <auto-generated by scripts/alignment/transcribe_muscle3_matrices.py; do not edit.',
           '// MUSCLE 3.8.1551 score matrices (vtml2.cpp VTML_LA / VTML_SP, mpam200.cpp PAM200, nucmx.cpp NUC_SP), amino-acid column order A C D E F G H I K L M N P Q R S T V W Y.',
           'namespace Seqeron.Genomics.Alignment;', '', 'public static partial class SequenceAligner', '{']
    for name, m, n, doc in (('MuscleVtmlLa', la, 20, 'VTML_LA (VTML200 likelihood ratios, the default of the LE profile score): <c>(float) literal</c>.'),
                            ('MuscleVtmlSp', sp, 20, 'VTML_SP (VTML240, -sv): <c>(float) (literal + 22.0f)</c> is applied by the loader.'),
                            ('MusclePam200', pam, 20, 'PAM200 (-sp): <c>(float) literal + 20.0f</c> is applied by the loader.'),
                            ('MuscleNucSp', nuc, 4, 'NUC_SP (BLASTZ default, nucleotides): <c>(float) literal + 60.0f</c> is applied by the loader.')):
        out += [f'    /// <summary>{doc}</summary>', f'    private static readonly double[] {name} =', '    {']
        for i in range(n):
            out.append('        ' + ', '.join((x if '.' in x else x + '.0') for x in m[i][:n]) + ',')
        out += ['    };', '']
    out.append('}')
    open(out_path, 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    if sys.argv[1] == '--dayhoff':
        t = open(os.path.join(sys.argv[2], 'msadistkimura.cpp')).read()
        body = re.sub(r'/\*.*?\*/', '', re.search(r'dayhoff_pams\[\]=\{(.*?)\};', t, re.S).group(1), flags=re.S)
        print(', '.join(re.findall(r'\d+', body)))
    else:
        main(sys.argv[1], sys.argv[2])
