#!/usr/bin/env python3
"""Extracts the amino-acid scoring tables (sw_alignscore.hh: BLOSUM 45 / 62 / 80, GOOD / OPEN / CONT gap scores) and the translation tables (translate.hh: transdna, compdna, universal) of the MUMmer 3.23 sources
(Debian source package mummer_3.23+dfsg.orig.tar.xz, src/tigr) and writes Seqeron.Genomics.Alignment/MummerPromerTables.cs. Usage: python3 extract_mummer_promer_tables.py <src/tigr dir> > MummerPromerTables.cs"""
import re, sys

d = sys.argv[1]
sc = open(d + '/sw_alignscore.hh').read()
tr = open(d + '/translate.hh').read()

# score matrices: four 26 x 26 blocks
body = sc[sc.index('const int MATCH_SCORE'):]
rows = re.findall(r'\{([-+0-9 ,]*)\}', body)
nums = [[int(x) for x in r.replace('+', '').split(',')] for r in rows if len(r.split(',')) == 26]
assert len(nums) == 4 * 26, len(nums)
mats = [nums[i * 26:(i + 1) * 26] for i in range(4)]

# transdna
t = tr[tr.index('const int\ttransdna[256]'):]
t = t[:t.index('};')]
names = {'BAD_PEP_CHAR': -1, 'SKIP_PEP_CHAR': -2, 'DNA_A': 0, 'DNA_C': 1, 'DNA_G': 2, 'DNA_TU': 3, 'DNA_M': 4, 'DNA_R': 5, 'DNA_W': 6, 'DNA_S': 7, 'DNA_Y': 8, 'DNA_K': 9, 'DNA_V': 10, 'DNA_H': 11, 'DNA_D': 12, 'DNA_B': 13, 'DNA_XN': 14, 'DNA_dot': 15}
trans = [names[m] for m in re.findall(r'\b(BAD_PEP_CHAR|SKIP_PEP_CHAR|DNA_[A-Za-z]+)\b,?\s*(?:/\*|$|\n)', t.split('{', 1)[1])]
assert len(trans) == 256, len(trans)
c = tr[tr.index('const int\tcompdna[NUM_DNA_SYMBOLS]'):]
c = c[:c.index('};')]
comp = [names[m] for m in re.findall(r'\b(DNA_[A-Za-z]+)\b', c.split('{', 1)[1])]
assert len(comp) == 16
u = tr[tr.index('const char\tuniversal['):]
u = u[:u.index('};')].split('{', 1)[1]
uni = ''.join(re.findall(r"'(.)'", u))
assert len(uni) == 4096, len(uni)

out = []
out.append('// <auto-generated> by scripts/alignment/extract_mummer_promer_tables.py from MUMmer 3.23 src/tigr/sw_alignscore.hh and translate.hh (Debian mummer_3.23+dfsg.orig.tar.xz). Do not edit by hand. </auto-generated>')
out.append('namespace Seqeron.Genomics.Alignment;\n')
out.append('/// <summary>The tables of the amino-acid half of MUMmer 3.23: the BLOSUM 45 / 62 / 80 matrices of <c>sw_alignscore.hh</c> (index 1 - 3; 0 is the nucleotide matrix) and the six-frame translation tables of <c>translate.hh</c>.</summary>')
out.append("internal static partial class MummerPromerTables\n{")
out.append('    /// <summary><c>GOOD_SCORE</c> per matrix type (NUCLEOTIDE, BLOSUM45, BLOSUM62, BLOSUM80).</summary>')
out.append('    public static readonly int[] GoodScore = [3, 10, 8, 8];\n')
out.append('    /// <summary><c>OPEN_GAP_SCORE</c> per matrix type.</summary>')
out.append('    public static readonly int[] OpenGapScore = [-10, -10, -10, -10];\n')
out.append('    /// <summary><c>CONT_GAP_SCORE</c> per matrix type.</summary>')
out.append('    public static readonly int[] ContGapScore = [-7, -1, -1, -1];\n')
out.append('    /// <summary><c>MATCH_SCORE [matrix] [a - \'A\'] [b - \'A\']</c> for the matrices BLOSUM 45 / 62 / 80 (index 0 = BLOSUM45), 26 x 26 row-major (the nucleotide matrix is computed by <see cref="NucmerSwAlign.MatchScore"/>).</summary>')
out.append('    public static readonly sbyte[][] Blosum =\n    [')
for m in mats[1:]:
    flat = [v for r in m for v in r]
    out.append('        [' + ', '.join(str(v) for v in flat) + '],')
out.append('    ];\n')
out.append('    /// <summary><c>transdna [256]</c>: BAD_PEP_CHAR = -1, SKIP_PEP_CHAR = -2, otherwise the DNA symbol index 0 - 15.</summary>')
out.append('    public static readonly sbyte[] TransDna = [' + ', '.join(str(v) for v in trans) + '];\n')
out.append('    /// <summary><c>compdna [16]</c>.</summary>')
out.append('    public static readonly sbyte[] CompDna = [' + ', '.join(str(v) for v in comp) + '];\n')
out.append('    /// <summary><c>universal [16 * 16 * 16]</c>: the amino acid of the codon (index = (first << 8) + (second << 4) + third).</summary>')
out.append('    public const string Universal =')
for i in range(0, 4096, 64):
    out.append('        "' + uni[i:i + 64].replace('\\', '\\\\').replace('"', '\\"') + '"' + (' +' if i + 64 < 4096 else ';'))
out.append('}')
print('\n'.join(out))
