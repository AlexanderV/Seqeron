#!/usr/bin/env python3
"""B09 audit A2-15: generates src/.../Seqeron.Genomics.Infrastructure/SubstitutionMatrix.EmbossData.cs and tests/.../TestData/Alignment/emboss_matrices_oracle.tsv from the EMBOSS 6.6.0 data directory.

    python3 scripts/alignment/generate_emboss_matrices.py [--data /usr/share/EMBOSS/data]

Reads every matrix file named in `Matrices.protein` / `Matrices.nucleotide` plus ENUC.4.4 (ENUC.4.2 is a rectangular 15 x 4 table and is skipped) (each: '#' comment lines, a header line of
residue letters, then one row per residue: `<label> <scores...>`) and writes
  * the C# data table (name, description, alphabet in file order, row-major scores) read by `SubstitutionMatrix.Get(name)`;
  * the oracle TSV `name \t alphabet \t row-major scores` (an independent copy for the cell-for-cell test) with the NCBI aliases checked against Biopython's substitution_matrices when Biopython is installed
    (BLOSUM45 / 50 / 62 / 80 / 90, PAM30 / 70 / 250, NUC.4.4: 0 differing cells on every common symbol).
"""
import argparse, os, re, sys

ap = argparse.ArgumentParser()
ap.add_argument('--data', default='/usr/share/EMBOSS/data')
a = ap.parse_args()
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
cs_path = os.path.join(root, 'src', 'Seqeron', 'Algorithms', 'Seqeron.Genomics.Infrastructure', 'SubstitutionMatrix.EmbossData.cs')
tsv_path = os.path.join(root, 'tests', 'Seqeron', 'Seqeron.Genomics.Tests', 'TestData', 'Alignment', 'emboss_matrices_oracle.tsv')


def listing(fn):
    out = {}
    for line in open(os.path.join(a.data, fn), encoding='utf-8'):
        if line.startswith('#') or not line.strip():
            continue
        name, _, desc = line.strip().partition(' ')
        out[name] = desc.strip()
    return out


def read_matrix(path):
    lines = [l.rstrip('\n') for l in open(path, encoding='utf-8') if not l.startswith('#') and l.strip()]
    header = lines[0].split()
    assert all(len(h) == 1 for h in header), (path, header)
    rows = {}
    for l in lines[1:]:
        t = l.split()
        rows[t[0]] = [int(x) for x in t[1:]]
    assert list(rows) == header, (path, list(rows), header)
    for k, v in rows.items():
        assert len(v) == len(header), (path, k, len(v))
    return ''.join(header), [rows[h] for h in header]


names = {}
names.update(listing('Matrices.protein'))
names.update(listing('Matrices.nucleotide'))
# ENUC.4.2 is NOT square (15 IUPAC rows x the 4 columns A T G C: the NCBI NUC.4.2 layout, not a symmetric pairwise table) and is therefore not representable as a SubstitutionMatrix.
for extra, desc in (('ENUC.4.4', 'Todd Lowe 12/10/92: ambiguous nucleotide codes, probabilities rounded to nearest integer (NCBI NUC.4.4, without U)'),):
    if os.path.exists(os.path.join(a.data, extra)):
        names.setdefault(extra, desc)
data = []
for name, desc in sorted(names.items(), key=lambda kv: (not kv[0].startswith('EBLOSUM'), kv[0].startswith('EPAM'), kv[0])):
    alphabet, rows = read_matrix(os.path.join(a.data, name))
    data.append((name, desc, alphabet, [v for r in rows for v in r]))

try:
    from Bio.Align import substitution_matrices as sm
    for ncbi, emboss in (('BLOSUM45', 'EBLOSUM45'), ('BLOSUM50', 'EBLOSUM50'), ('BLOSUM62', 'EBLOSUM62'), ('BLOSUM80', 'EBLOSUM80'), ('BLOSUM90', 'EBLOSUM90'),
                         ('PAM30', 'EPAM30'), ('PAM70', 'EPAM70'), ('PAM250', 'EPAM250'), ('NUC.4.4', 'ENUC.4.4')):
        m = sm.load(ncbi)
        _, _, alphabet, flat = next(d for d in data if d[0] == emboss)
        n = len(alphabet)
        diff = sum(1 for i, x in enumerate(alphabet) for j, y in enumerate(alphabet) if x in m.alphabet and y in m.alphabet and m[x, y] != flat[i * n + j])
        print(f'Biopython {ncbi} vs {emboss}: {diff} differing cells')
        assert diff == 0
except ImportError:
    print('Biopython not installed: alias check skipped')

with open(cs_path, 'w', newline='\n', encoding='utf-8') as f:
    f.write('// <auto-generated by scripts/alignment/generate_emboss_matrices.py from the EMBOSS 6.6.0 data directory (/usr/share/EMBOSS/data); do not edit.\n')
    f.write('// Every EMBOSS residue-pair comparison matrix named in Matrices.protein / Matrices.nucleotide (+ ENUC.4.4): name, description, alphabet in file order, row-major scores.\n')
    f.write('namespace Seqeron.Genomics.Infrastructure;\n\npublic sealed partial class SubstitutionMatrix\n{\n')
    f.write('    private static readonly (string Name, string Description, string Alphabet, string Scores)[] EmbossData =\n    [\n')
    for name, desc, alphabet, flat in data:
        f.write(f'        ("{name}", "{desc}", "{alphabet}", "{" ".join(map(str, flat))}"),\n')
    f.write('    ];\n}\n')
with open(tsv_path, 'w', newline='\n', encoding='utf-8') as f:
    f.write('name\talphabet\tscores\n')
    for name, desc, alphabet, flat in data:
        f.write(f'{name}\t{alphabet}\t{" ".join(map(str, flat))}\n')
print(len(data), 'matrices;', os.path.getsize(cs_path), 'bytes of C#')
