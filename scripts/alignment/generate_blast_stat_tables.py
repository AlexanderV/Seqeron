#!/usr/bin/env python3
"""Generates src/Seqeron/Algorithms/Seqeron.Genomics.Alignment/AlignmentSignificance.Tables.cs (audit R14-7, B09 F300) from NCBI's blast_stat.c.

Source (opened, User-Agent Seqeron-review/1.0): https://raw.githubusercontent.com/ncbi/ncbi-cxx-toolkit-public/master/src/algo/blast/core/blast_stat.c
The Karlin-Altschul / Gumbel parameter tables of the standard protein matrices (rows: gap existence, extension, decline-to-align, Lambda, K, H, alpha, beta, C, alpha_v, sigma; the first row of each matrix
is the ungapped one) and of the blastn reward / penalty pairs (rows: gap existence, extension, Lambda, K, H, alpha, beta, theta).

  python3 scripts/alignment/generate_blast_stat_tables.py [path/to/blast_stat.c]     (downloads the file when no path is given)
"""
import os
import re
import sys
import urllib.request

URL = "https://raw.githubusercontent.com/ncbi/ncbi-cxx-toolkit-public/master/src/algo/blast/core/blast_stat.c"
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir, os.pardir))
OUT = os.path.join(ROOT, "src", "Seqeron", "Algorithms", "Seqeron.Genomics.Alignment", "AlignmentSignificance.Tables.cs")
PROTEIN = ["blosum45", "blosum50", "blosum62", "blosum80", "blosum90", "pam30", "pam70", "pam250"]
NUCL = ["1_5", "1_4", "2_7", "1_3", "2_5", "1_2", "2_3", "3_4", "4_5", "1_1", "3_2", "5_4"]


def rows(block):
    out = []
    for m in re.finditer(r"\{([^{}]+)\}", block):
        vals = []
        for tok in m.group(1).split(","):
            tok = tok.strip().replace("(double) INT2_MAX", "32767")
            if tok:
                vals.append(float(tok))
        out.append(vals)
    return out


def fmt(vals):
    return ", ".join(repr(int(v)) if float(v).is_integer() and abs(v) < 1e5 and "." not in repr(v) else repr(v) for v in vals)


def main(argv):
    if len(argv) > 0:
        text = open(argv[0], encoding="utf-8").read()
    else:
        req = urllib.request.Request(URL, headers={"User-Agent": "Seqeron-review/1.0"})
        text = urllib.request.urlopen(req, timeout=60).read().decode("utf-8")
    lines = ["// <auto-generated> scripts/alignment/generate_blast_stat_tables.py from NCBI blast_stat.c (" + URL + "); do not edit by hand. </auto-generated>",
             "namespace Seqeron.Genomics.Alignment;", "",
             "public static partial class AlignmentSignificance", "{",
             "    // protein: { gap existence, gap extension, decline-to-align (ignored), Lambda, K, H, alpha, beta, C, alpha_v, sigma }; the first row is the ungapped one (existence / extension 32767)",
             "    private static readonly Dictionary<string, double[][]> ProteinTables = new(StringComparer.OrdinalIgnoreCase)", "    {"]
    for name in PROTEIN:
        m = re.search(r"static array_of_8 %s_values\[[A-Z0-9_]+\] = \{(.*?)\n\};" % name, text, re.S)
        r = rows(m.group(1))
        assert all(len(x) == 11 for x in r), name
        lines.append('        ["%s"] =' % name.upper())
        lines.append("        [")
        for x in r:
            lines.append("            [%s]," % fmt(x))
        lines.append("        ],")
    lines += ["    };", "",
              "    // nucleotide: per (reward, penalty) { gap existence, gap extension, Lambda, K, H, alpha, beta, theta }; a first row with existence 0 and extension 0 is the linear-gap row (kept first)",
              "    private static readonly Dictionary<(int Reward, int Penalty), double[][]> NucleotideTables = new()", "    {"]
    for key in NUCL:
        m = re.search(r"static const array_of_8 blastn_values_%s\[\] = \{(.*?)\n\};" % key, text, re.S)
        r = rows(m.group(1))
        assert all(len(x) == 8 for x in r), key
        a, b = key.split("_")
        lines.append("        [(%s, -%s)] =" % (a, b))
        lines.append("        [")
        for x in r:
            lines.append("            [%s]," % fmt(x))
        lines.append("        ],")
    lines += ["    };", "}", ""]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main(sys.argv[1:])
