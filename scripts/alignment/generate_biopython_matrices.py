#!/usr/bin/env python3
"""Generates src/Seqeron/Algorithms/Seqeron.Genomics.Infrastructure/SubstitutionMatrix.BiopythonData.cs (audit R14-8, B09 F301) from the data files of the installed Biopython 1.88
(`Bio/Align/substitution_matrices/data`): the named matrices that were not built in (BENNER6 / 22 / 74, BLASTN, BLASTP, DAYHOFF, FENG, GENETIC, GONNET1992, HOXD70, JOHNSON, JONES, LEVIN, MCLACHLAN,
MDM78, MEGABLAST, RAO, RISLER, STR, TRANS) and the 64 x 64 codon matrix SCHNEIDER. The cells are written as the decimal text of the data file (exact: at most two decimals), so the C# side parses them
as `decimal`; the header comments of the files (source, citation) are kept as the description.

  python3 scripts/alignment/generate_biopython_matrices.py
"""
import os

import Bio

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir, os.pardir))
OUT = os.path.join(ROOT, "src", "Seqeron", "Algorithms", "Seqeron.Genomics.Infrastructure", "SubstitutionMatrix.BiopythonData.cs")
DATA = os.path.join(os.path.dirname(Bio.__file__), "Align", "substitution_matrices", "data")
NAMES = ["BENNER22", "BENNER6", "BENNER74", "BLASTN", "BLASTP", "DAYHOFF", "FENG", "GENETIC", "GONNET1992", "HOXD70", "JOHNSON", "JONES", "LEVIN", "MCLACHLAN", "MDM78", "MEGABLAST", "RAO", "RISLER", "STR", "TRANS"]


def read(name):
    comments, rows = [], []
    for line in open(os.path.join(DATA, name), encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("#"):
            comments.append(line.lstrip("# ").strip())
        elif line.strip():
            rows.append(line.split())
    header = rows[0]
    body = rows[1:]
    assert [r[0] for r in body] == header, name
    values = [tok for r in body for tok in r[1:]]
    assert len(values) == len(header) ** 2, name
    return header, values, " ".join(c for c in comments if c)[:300]


def main():
    out = ["// <auto-generated> scripts/alignment/generate_biopython_matrices.py from Biopython 1.88 Bio/Align/substitution_matrices/data; do not edit by hand. </auto-generated>",
           "namespace Seqeron.Genomics.Infrastructure;", "", "public sealed partial class SubstitutionMatrix", "{",
           "    // (name, alphabet, description, cells in row order as the decimal text of the data file)",
           "    private static readonly (string Name, string Alphabet, string Description, string Scores)[] BiopythonData =", "    ["]
    for n in NAMES:
        header, values, desc = read(n)
        assert all(len(h) == 1 for h in header), n
        out.append('        ("%s", "%s", "%s", "%s"),' % (n, "".join(header), desc.replace('"', "'"), " ".join(values)))
    out += ["    ];", "}", "",
            "public sealed partial class CodonSubstitutionMatrix", "{"]
    header, values, desc = read("SCHNEIDER")
    out.append('    private const string SchneiderDescription = "%s";' % desc.replace('"', "'"))
    out.append('    private const string SchneiderCodons = "%s";' % " ".join(header))
    out.append('    private const string SchneiderScores = "%s";' % " ".join(values))
    out += ["}", ""]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
