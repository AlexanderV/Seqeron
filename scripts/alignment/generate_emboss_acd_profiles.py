#!/usr/bin/env python3
"""A6-2 (B09 F177): the qualifier universe of the ported EMBOSS 6.6.0 programs, read from `<program> -help -verbose`, as the C# table
src/Seqeron/Algorithms/Seqeron.Genomics.Infrastructure/EmbossAcdProfiles.g.cs.

The ACD command-line resolver (ajacd.c acdArgsParse / acdIsQual / acdFindQualDetail / acdFindQualAssoc / acdFindQualMaster) matches a qualifier against EVERY qualifier of the program (parameters,
standard / additional / advanced qualifiers, the associated qualifiers of each parameter with their number, the general qualifiers): an abbreviation is only valid when it is unique among all of them
(`-se` is ambiguous between `-send` and `-sequence` in fuzznuc, not in needle). So the port needs the whole list of each program, not only the sequence qualifiers.
Line format of the table:  P name pnum type  (a parameter)  |  Q name type  (a standard / additional / advanced qualifier)  |  A master name pnum type  (an associated qualifier of `master`, pnum 0 = unnumbered)  |  G name type  (a general qualifier).
Usage: python3 scripts/alignment/generate_emboss_acd_profiles.py > src/Seqeron/Algorithms/Seqeron.Genomics.Infrastructure/EmbossAcdProfiles.g.cs   (needs the EMBOSS 6.6.0 programs on PATH)
"""
import re, subprocess, sys

PROGRAMS = ['needle', 'water', 'stretcher', 'matcher', 'supermatcher', 'needleall', 'merger', 'megamerger', 'seqmatchall', 'fuzznuc', 'fuzzpro', 'fuzztran', 'etandem', 'equicktandem', 'dotmatcher', 'distmat', 'diffseq', 'wordmatch', 'est2genome', 'seqret', 'extractfeat', 'showfeat', 'featreport', 'twofeat', 'maskfeat', 'coderet', 'union', 'descseq', 'seqretsplit', 'entret',
            'getorf', 'sixpack', 'showorf', 'checktrans', 'tcode', 'plotorf', 'showseq', 'prettyseq', 'revseq', 'transeq', 'extractseq', 'cutseq', 'degapseq', 'trimseq', 'trimspace', 'trimest', 'vectorstrip', 'skipseq',
            'nthseq', 'nthseqset', 'notseq', 'pasteseq', 'listor', 'msbar', 'shuffleseq', 'maskseq', 'maskambignuc', 'maskambigprot', 'nospace', 'notab', 'noreturn', 'makenucseq', 'makeprotseq', 'newseq', 'infoseq',
            'seqcount', 'wordcount', 'wordfinder', 'splitter', 'yank', 'seqxref', 'patmatmotifs', 'patmatdb', 'preg', 'dreg', 'tfscan', 'marscan', 'prosextract', 'plotcon', 'drfinddata', 'dbtell', 'showdb']


def profile(prog):
    text = subprocess.run([prog, '-help', '-verbose'], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True).stdout
    out = []
    section = None
    master = None
    for line in text.split('\n'):
        if re.match(r'^\s+(Standard|Additional|Advanced)', line): section = 'Q'; master = None; continue
        if re.match(r'^\s+Associated qualifiers', line): section = 'A'; master = None; continue
        if re.match(r'^\s+General qualifiers', line): section = 'G'; master = None; continue
        m = re.match(r'^\s+"-(\w+)" associated qualifiers', line)
        if m: master = m.group(1); continue
        if section == 'Q':
            m = re.match(r'^[ *]*\[-(\w+)\]\s+(\w+)', line)
            if m:
                out.append(('P', m.group(1), m.group(2))); continue
            m = re.match(r'^[ *]  -(?:\[no\])?(\w+)\s+(\w+)', line)
            if m: out.append(('Q', m.group(1), m.group(2)))
        elif section == 'A' and master:
            m = re.match(r'^   -([a-z]+)(\d*)\s+(\w+)', line)
            if m: out.append(('A', master, m.group(1), int(m.group(2) or 0), m.group(3)))
        elif section == 'G':
            m = re.match(r'^   -(?:\[no\])?(\w+)\s+(\w+)', line)
            if m: out.append(('G', m.group(1), m.group(2)))
    # the parameter number is the order of the parameters
    lines, n = [], 0
    for item in out:
        if item[0] == 'P':
            n += 1
            lines.append('P %s %d %s' % (item[1], n, item[2]))
        elif item[0] == 'A':
            lines.append('A %s %s %d %s' % item[1:])
        else:
            lines.append('%s %s %s' % item)
    return lines


def main():
    print('// <auto-generated> by scripts/alignment/generate_emboss_acd_profiles.py from `<program> -help -verbose` (EMBOSS 6.6.0.0); do not edit </auto-generated>')
    print('namespace Seqeron.Genomics.Infrastructure;')
    print()
    print('internal static partial class EmbossAcdProfiles')
    print('{')
    print('    private static readonly (string Program, string Items)[] Table =')
    print('    [')
    for p in PROGRAMS:
        print('        ("%s", """' % p)
        for l in profile(p):
            print('            ' + l)
        print('            """),')
    print('    ];')
    print('}')


if __name__ == '__main__':
    main()
