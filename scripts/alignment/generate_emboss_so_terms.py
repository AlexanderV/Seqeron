#!/usr/bin/env python3
"""A5-8c3e (B09 F241): the terms of the Sequence Ontology file of EMBOSS 6.6.0 (data/OBO/so.obo) as C# data (src/Seqeron/Algorithms/Seqeron.Genomics.Infrastructure/EmbossSoTerms.g.cs): id, name and the obsolete flag of every [Term].
The EMBL / GenBank feature writers look the type of a feature up there (ajOboinQryS) when the EMBL vocabulary has no key for it and write `/note="*Type SO:id name"` (an obsolete term gives no note).
Usage: python3 scripts/alignment/generate_emboss_so_terms.py OUT.g.cs      (needs the EMBOSS 6.6.0 data files in /usr/share/EMBOSS/data)
"""
import sys


def main(out):
    terms, cur = [], None
    for raw in open('/usr/share/EMBOSS/data/OBO/so.obo', encoding='latin-1'):
        line = raw.rstrip('\n')
        if line == '[Term]':
            cur = {'id': None, 'name': None, 'obs': False}; terms.append(cur)
        elif line.startswith('['):
            cur = None
        elif cur is not None:
            if line.startswith('id: ') and cur['id'] is None: cur['id'] = line[4:]
            elif line.startswith('name: ') and cur['name'] is None: cur['name'] = line[6:]
            elif line.startswith('is_obsolete: true'): cur['obs'] = True
    rows = ['    ("%s", "%s", %s),' % (t['id'], (t['name'] or '').replace('\\', '\\\\').replace('"', '\\"'), 'true' if t['obs'] else 'false') for t in terms if t['id']]
    text = ('// <auto-generated by scripts/alignment/generate_emboss_so_terms.py: do not edit>\nnamespace Seqeron.Genomics.Infrastructure;\n\n'
            '/// <summary>The terms of the Sequence Ontology file of EMBOSS 6.6.0 (A5-8c3e, B09 F241).</summary>\ninternal static partial class EmbossSoTerms\n{\n'
            '    private static readonly (string Id, string Name, bool Obsolete)[] Data =\n    [\n' + '\n'.join(rows) + '\n    ];\n}\n')
    open(out, 'w', encoding='utf-8', newline='\n').write(text)


main(sys.argv[1])
