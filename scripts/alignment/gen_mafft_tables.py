#!/usr/bin/env python3
"""Extracts the numeric tables of MAFFT 7.505 (core/JTT.c, core/miyata.h) into SequenceAligner.MafftTables2.cs.
Usage: python3 scripts/alignment/gen_mafft_tables.py <mafft-7.505-source>/core   (the Debian mafft_7.505.orig.tar.gz, dir 'mafft-7.505-without-extensions/core')"""
import re, sys, os
core = sys.argv[1]
jtt = open(os.path.join(core, 'JTT.c'), encoding='latin-1').read()
fft = open(os.path.join(core, 'miyata.h'), encoding='latin-1').read()
r = [[0.0] * 20 for _ in range(20)]
for i, j, v in re.findall(r'r\[\s*(\d+)\]\[\s*(\d+)\]\s*=\s*(-?\d+(?:\.\d+)?)\s*;', jtt):
    r[int(i)][int(j)] = float(v)

def arr(src, name):
    m = re.search(name + r'\s*\[\s*(?:20)?\s*\]\s*=\s*\{([^}]*)\}', src)
    return [float(x) for x in re.findall(r'-?\d+\.\d+|-?\d+', re.sub(r'/\*.*?\*/', '', m.group(1)))]

freq0 = arr(jtt, 'freq0')
freqtm = arr(jtt, 'freq0_TM')
pol = arr(fft, 'polarity_')
vol = arr(fft, 'volume_')
assert len(freq0) == len(freqtm) == len(pol) == len(vol) == 20

def d(v):
    s = repr(float(v))
    return s

lines = []
lines.append('// <auto-generated> by scripts/alignment/gen_mafft_tables.py from MAFFT 7.505 core/JTT.c and core/miyata.h </auto-generated>')
lines.append('namespace Seqeron.Genomics.Alignment;')
lines.append('')
lines.append('public static partial class SequenceAligner')
lines.append('{')
lines.append('    internal static class MafftTables2')
lines.append('    {')
lines.append('        /// <summary>JTT.c: the 20 x 20 table r[i][j] before normalisation: the lower triangle holds the JTT accepted point mutations, the upper triangle those of the transmembrane model (--tm).</summary>')
lines.append('        internal static readonly double[][] JttAcceptedMutations = new[]')
lines.append('        {')
for row in r:
    lines.append('            new[] { ' + ', '.join(d(v) for v in row) + ' },')
lines.append('        };')
lines.append('')
lines.append('        internal static readonly double[] JttFrequencies = { ' + ', '.join(d(v) for v in freq0) + ' };')
lines.append('        internal static readonly double[] TmFrequencies = { ' + ', '.join(d(v) for v in freqtm) + ' };')
lines.append('        /// <summary>miyata.h polarity_ (Grantham) and volume_ per amino acid in the order ARNDCQEGHILKMFPSTWYV.</summary>')
lines.append('        internal static readonly double[] Polarity = { ' + ', '.join(d(v) for v in pol) + ' };')
lines.append('        internal static readonly double[] Volume = { ' + ', '.join(d(v) for v in vol) + ' };')
lines.append('    }')
lines.append('}')
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'Seqeron', 'Algorithms', 'Seqeron.Genomics.Alignment', 'SequenceAligner.MafftTables2.cs')
open(out, 'w').write('\n'.join(lines) + '\n')
print('wrote', out)
