using System.Reflection;
using NUnit.Framework;
using Seqeron.Genomics.Alignment;
using Seqeron.Genomics.Core;
using Seqeron.Genomics.Infrastructure;

namespace Seqeron.Genomics.Tests.Unit.Alignment;

/// <summary>
/// ALIGN-GLOBAL-001 / ALIGN-LOCAL-001 / ALIGN-SEMI-001 (audit R14-15, B09 F294): every public pairwise aligner of <see cref="SequenceAligner"/> has an overload with an explicit trailing
/// <see cref="CancellationToken"/> (generated by <c>scripts/alignment/generate_cancellable_overloads.py</c>); before only the linear <c>GlobalAlign</c> string / DnaSequence overloads had one, the others honoured the
/// ambient <see cref="SequenceAligner.WithCancellation{T}(CancellationToken, Func{T})"/> scope only. The overload enters that scope and calls the original: the result with a live token equals the original, a cancelled token throws
/// <see cref="OperationCanceledException"/> before any work, and a token cancelled mid-run stops the dynamic program at its next poll.
/// </summary>
[TestFixture]
[Category("Alignment")]
[Category("ALIGN-GLOBAL-001")]
[NonParallelizable]
public class SequenceAligner_CancellationOverloads_Tests
{

    private static IEnumerable<TestCaseData> Families()
    {
        yield return Case("LocalAlignTopN", ct => EmbossPairwisePrograms.LocalAlignTopN(A, B, Scalar, 3, 1, TopNTieOrder.WatermanEggert, ct)[0], () => EmbossPairwisePrograms.LocalAlignTopN(A, B, Scalar, 3, 1, TopNTieOrder.WatermanEggert)[0]);
        yield return Case("LocalAlignAffineTopN(Sim)", ct => EmbossPairwisePrograms.LocalAlignAffineTopN(A, B, Matrix, 2, 0, TopNTieOrder.Sim, ct)[0], () => EmbossPairwisePrograms.LocalAlignAffineTopN(A, B, Matrix, 2, 0, TopNTieOrder.Sim)[0]);
        yield return Case("NeedleAlign", ct => EmbossPairwisePrograms.NeedleAlign(A, B, null, 10, 0.5, false, 10, 0.5, ct), () => EmbossPairwisePrograms.NeedleAlign(A, B));
        yield return Case("WaterAlign", ct => EmbossPairwisePrograms.WaterAlign(A, B, null, 10, 0.5, ct), () => EmbossPairwisePrograms.WaterAlign(A, B));
        yield return Case("StretcherAlign", ct => EmbossPairwisePrograms.StretcherAlign(A, B, null, null, null, ct), () => EmbossPairwisePrograms.StretcherAlign(A, B));
    }

    [Test]
    public void CancelledWhileRunning_ExplicitTokenOverloads_StopAtTheNextPoll()
    {
        string a = Random(600, 71), b = Random(600, 72);
        Assert.That(PollCancellation.CancelInside(ct => SequenceAligner.LocalAlignAffine(a, b, new MatrixScoring(SubstitutionMatrix.EdnaFull, -5, -2), ct), "AffineFill"), Does.Contain("AffineFill"));
        Assert.That(PollCancellation.CancelInside(ct => SequenceAligner.GlobalAlignAffine(a, b, new ScoringMatrix(2, -1, -3, -1), ct), "AffineFill"), Does.Contain("AffineFill"));
        Assert.That(PollCancellation.CancelInside(ct => EmbossPairwisePrograms.LocalAlignTopN(a, b, new ScoringMatrix(2, -1, -3, -1), 5, 1, TopNTieOrder.WatermanEggert, ct), "LocalDeclumper"), Does.Contain("LocalDeclumper"));
        Assert.That(PollCancellation.CancelInside(ct => EmbossPairwisePrograms.NeedleAlign(a, b, null, 10, 0.5, false, 10, 0.5, ct), "NeedleCore"), Does.Contain("NeedleCore"));
        Assert.That(PollCancellation.CancelInside(ct => EmbossPairwisePrograms.WaterAlign(a, b, null, 10, 0.5, ct), "WaterCore"), Does.Contain("WaterCore"));
    }

    [Test]
    public void NullSequences_StillThrowTheArgumentException_OfTheOriginal()
    {
        Assert.Throws<ArgumentNullException>(() => SequenceAligner.LocalAlign((string)null!, B, Scalar, CancellationToken.None));
        Assert.Throws<ArgumentNullException>(() => EmbossPairwisePrograms.NeedleAlign(A, null!, null, 10, 0.5, false, 10, 0.5, CancellationToken.None));
    }

    private static TestCaseData Case(string name, Func<CancellationToken, AlignmentResult> withToken, Func<AlignmentResult> plain)
        => new TestCaseData(withToken, plain).SetName("Overload_" + name.Replace('(', '_').Replace(")", ""));

    private const string B = "ACGTCGTTAGCACGT";

    private static readonly ScoringMatrix Scalar = new(2, -1, -3, -1);

    private const string A = "ACGTACGTTAGCACGGT";

    private static readonly MatrixScoring Matrix = new(SubstitutionMatrix.EdnaFull, -5, -2);

    private static string Random(int n, int seed)
    {
        var rng = new System.Random(seed);
        return new string(Enumerable.Range(0, n).Select(_ => "ACGT"[rng.Next(4)]).ToArray());
    }

    [TestCaseSource(nameof(Families))]
    public void TokenOverload_EqualsTheOriginal_AndAPreCancelledTokenThrows(Func<CancellationToken, AlignmentResult> withToken, Func<AlignmentResult> plain)
    {
        using var cts = new CancellationTokenSource();
        Assert.That(withToken(cts.Token), Is.EqualTo(plain()));
        Assert.That(withToken(CancellationToken.None), Is.EqualTo(plain()));
        Assert.Throws<OperationCanceledException>(() => withToken(Cancelled));
    }

    private static readonly CancellationToken Cancelled = new(true);
}
