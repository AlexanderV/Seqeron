    // C-AMPCF-1 — R fails on one sample and on a single-probe chromosome (Tumor_LogR[chr[[k]], ] drops to a vector:
    // "incorrect number of subscripts on matrix"); both are rejected, as are inconsistent inputs.
    [Test]
    public void SegmentAlleleSpecificAsMultiPcf_InvalidArguments_Throw()
    {
        var (samples, het) = Simulate(C5);
        var twoSamples = samples;
        var shifted = samples[1].Select(l => l with { Position = l.Position + 1 }).ToList();
        var singleProbeChr = samples.Select(s => (IReadOnlyList<OncologyAnalyzer.AlleleSpecificLocus>)s
            .Append(new OncologyAnalyzer.AlleleSpecificLocus("3", 999_000_000, 0.0, 0.5)).ToList()).ToList();

        Assert.Multiple(() =>
        {
            Assert.Throws<ArgumentNullException>(() => OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(null!));
            Assert.Throws<ArgumentException>(() => OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(new[] { samples[0] }, het),
                "One sample: R fails; use SegmentAlleleSpecificAspcf.");
            Assert.Throws<ArgumentException>(() => OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(singleProbeChr),
                "Single-probe chromosome: R fails.");
            Assert.Throws<ArgumentException>(() => OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(new[] { samples[0], shifted }, het),
                "Different probe sets.");
            Assert.Throws<ArgumentException>(() => OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(twoSamples, het.Take(10).ToList()));
            Assert.Throws<ArgumentException>(() => OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(
                twoSamples, het, 70.0, Opt(new[] { 1.0, 1.0, 1.0 })), "wsample length must be S or 2S.");
            Assert.Throws<ArgumentOutOfRangeException>(() => OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(
                twoSamples, het, 70.0, Opt(new[] { 1.0, -1.0 })));
            Assert.Throws<ArgumentOutOfRangeException>(() => OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(twoSamples, het, 0.0));
            Assert.Throws<ArgumentOutOfRangeException>(() => OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(twoSamples, het, double.NaN));
            var badBaf = samples[1].Select((l, i) => i == 0 ? l with { BAF = 1.5 } : l).ToList();
            var allHet = het.Select(_ => true).ToList();
            Assert.Throws<ArgumentException>(() => OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(new[] { samples[0], badBaf }, allHet));
            var badLogR = samples[1].Select((l, i) => i == 0 ? l with { LogR = double.PositiveInfinity } : l).ToList();
            Assert.Throws<ArgumentException>(() => OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(new[] { samples[0], badLogR }, het),
                "Infinite logR (NaN = R NA is accepted since B24 F59).");
        });
    }
