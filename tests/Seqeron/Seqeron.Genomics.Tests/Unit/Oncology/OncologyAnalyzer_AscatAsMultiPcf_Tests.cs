    /// <summary>
    /// Per probe: one MINSTD draw for the shared germline genotype (homozygous when forced or u &lt; pHom), then per sample 9
    /// draws (4 × logR noise, BAF orientation, 4 × BAF noise): logR = r + 0.2·(Σ4u − 2); heterozygous BAF = b (or 1 − b) +
    /// 0.1·(Σ4u − 2) clamped to [0, 1]; homozygous BAF = 0 or 1. Position = 1000·index (1-based).
    /// </summary>
    internal static (List<IReadOnlyList<OncologyAnalyzer.AlleleSpecificLocus>> Samples, List<bool> Het) Simulate(Cohort c)
    {
        double s = c.Seed;
        double U()
        {
            s = (s * 48271.0) % 2147483647.0;
            return s / 2147483647.0;
        }

        var samples = new List<List<OncologyAnalyzer.AlleleSpecificLocus>>();
        for (int k = 0; k < c.Samples; k++)
        {
            samples.Add(new List<OncologyAnalyzer.AlleleSpecificLocus>());
        }

        var het = new List<bool>();
        foreach (Block block in c.Blocks)
        {
            for (int p = 0; p < block.N; p++)
            {
                bool hom = U() < c.PHom || block.ForceHom;
                long position = (het.Count + 1) * 1000L;
                for (int k = 0; k < c.Samples; k++)
                {
                    double a1 = U(), a2 = U(), a3 = U(), a4 = U(), us = U(), c1 = U(), c2 = U(), c3 = U(), c4 = U();
                    double x = block.R[k] + 0.2 * ((((a1 + a2) + a3) + a4) - 2.0);
                    double y;
                    if (hom)
                    {
                        y = us < 0.5 ? 0.0 : 1.0;
                    }
                    else
                    {
                        double b0 = us < 0.5 ? 1.0 - block.B[k] : block.B[k];
                        y = Math.Min(1.0, Math.Max(0.0, b0 + 0.1 * ((((c1 + c2) + c3) + c4) - 2.0)));
                    }

                    samples[k].Add(new OncologyAnalyzer.AlleleSpecificLocus(block.Chrom, position, x, y));
                }

                het.Add(!hom);
            }
        }

        return (samples.Cast<IReadOnlyList<OncologyAnalyzer.AlleleSpecificLocus>>().ToList(), het);
    }

    private static IReadOnlyList<OncologyAnalyzer.AspcfSegmentation> Run(
        Cohort c, double penalty = 70.0, OncologyAnalyzer.AsMultiPcfOptions? options = null)
    {
        var (samples, het) = Simulate(c);
        return OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(samples, het, penalty, options);
    }

