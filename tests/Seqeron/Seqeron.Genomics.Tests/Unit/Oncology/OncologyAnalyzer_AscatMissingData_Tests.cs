    // C-ANA-1 — NaN (R NA) is accepted in logR and heterozygous BAF; infinities and out-of-range BAF still throw.
    [Test]
    public void Segmentation_NonFiniteInput_NaNAcceptedInfinityThrows()
    {
        var (samples, het) = SimulateWithNa(N1);
        var allHet = het.Select(_ => true).ToList();
        IReadOnlyList<OncologyAnalyzer.AlleleSpecificLocus> With(int i, double logR, double baf) =>
            samples[1].Select((l, k) => k == i ? l with { LogR = logR, BAF = baf } : l).ToList();

        Assert.Multiple(() =>
        {
            Assert.DoesNotThrow(() => OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(new[] { samples[0], With(0, double.NaN, double.NaN) }, allHet));
            Assert.DoesNotThrow(() => OncologyAnalyzer.SegmentAlleleSpecificAspcf(With(0, double.NaN, double.NaN), allHet));
            foreach (double bad in new[] { double.PositiveInfinity, double.NegativeInfinity })
            {
                Assert.Throws<ArgumentException>(() => OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(new[] { samples[0], With(0, bad, 0.5) }, allHet));
                Assert.Throws<ArgumentException>(() => OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(new[] { samples[0], With(0, 0.0, bad) }, allHet));
                Assert.Throws<ArgumentException>(() => OncologyAnalyzer.SegmentAlleleSpecificAspcf(With(0, bad, 0.5), allHet));
                Assert.Throws<ArgumentException>(() => OncologyAnalyzer.SegmentAlleleSpecificAspcf(With(0, 0.0, bad), allHet));
            }

            Assert.Throws<ArgumentException>(() => OncologyAnalyzer.SegmentAlleleSpecificAspcf(With(0, double.NaN, 0.5), 70.0),
                "The all-heterozygous fastAspcf overload (not the ascat.aspcf driver) still requires complete data.");
        });
    }
