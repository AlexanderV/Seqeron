    /// <summary>Simulate (OncologyAnalyzer_AscatAsMultiPcf_Tests) + the NaN rules (R applyNA in the Evidence file).</summary>
    private static (List<IReadOnlyList<OncologyAnalyzer.AlleleSpecificLocus>> Samples, List<bool> Het) SimulateWithNa(NaCohort c)
    {
        var (samples, het) = Simulate(c.Cohort);
        var data = samples.Select(s => s.ToArray()).ToArray();
        foreach (NaRule rule in c.Rules)
        {
            int hetCounter = 0;
            for (int i = 0; i < het.Count; i++)
            {
                if (het[i])
                {
                    hetCounter++;
                }

                if (!rule.Applies(i + 1, data[0][i].Chromosome, hetCounter, !het[i]))
                {
                    continue;
                }

                foreach (int s in rule.Samples)
                {
                    data[s][i] = data[s][i] with
                    {
                        LogR = rule.LogR ? double.NaN : data[s][i].LogR,
                        BAF = rule.Baf ? double.NaN : data[s][i].BAF,
                    };
                }
            }
        }

        return (data.Select(d => (IReadOnlyList<OncologyAnalyzer.AlleleSpecificLocus>)d).ToList(), het);
    }

    private static IReadOnlyList<OncologyAnalyzer.AspcfSegmentation> Segment(NaCohort c, bool multi)
    {
        var (samples, het) = SimulateWithNa(c);
        return multi
            ? OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(samples, het)
            : samples.Select(s => OncologyAnalyzer.SegmentAlleleSpecificAspcf(s, het)).ToList();
    }

