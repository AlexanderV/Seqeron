        var result = Segment(cohort, multi);
        Track[] expected = Expected[id + (multi ? "Multi" : "Single")];
        Assert.That(result, Has.Count.EqualTo(expected.Length));

        Assert.Multiple(() =>
        {
            for (int s = 0; s < expected.Length; s++)
            {
                int n = het.Count;
                var logR = new double[n];
                foreach (Run run in expected[s].LogR)
                {
                    Array.Fill(logR, run.Value, run.Start - 1, run.Length);
                }

                var baf = new double[n];
                Array.Fill(baf, double.NaN);
                var missing = new HashSet<int>(expected[s].MissingHet);
                var present = Enumerable.Range(0, n).Where(i => het[i] && !missing.Contains(i + 1)).ToArray();
                foreach (Run run in expected[s].PresentBaf)
                {
                    for (int k = run.Start - 1; k < run.Start - 1 + run.Length; k++)
                    {
                        baf[present[k]] = run.Value;
                    }
                }

                Assert.That(present, Has.Length.EqualTo(expected[s].PresentBaf.Sum(r => r.Length)), $"S{s + 1}: BAF site count.");
                for (int i = 0; i < n; i++)
                {
                    Assert.That(result[s].SegmentedLogR[i], Is.EqualTo(logR[i]), $"S{s + 1} probe {i + 1}: logR.");
                    if (double.IsNaN(baf[i]))
                    {
                        Assert.That(double.IsNaN(result[s].SegmentedBaf[i]), Is.True, $"S{s + 1} probe {i + 1}: BAF NA.");
                    }
                    else
                    {
                        Assert.That(result[s].SegmentedBaf[i], Is.EqualTo(baf[i]), $"S{s + 1} probe {i + 1}: BAF.");
                    }
                }

                // Breakpoints: identical runs of segmented logR (exact equality inside a run).
                for (int i = 1; i < n; i++)
                {
                    Assert.That(result[s].SegmentedLogR[i] == result[s].SegmentedLogR[i - 1], Is.EqualTo(logR[i] == logR[i - 1]),
                        $"S{s + 1} probe {i + 1}: breakpoint.");
                }
            }
        });
    }

