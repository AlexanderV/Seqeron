    // C-MALEX-1 — argument contract.
    [Test]
    public void MaleXNonParRegenotyping_InvalidArguments_Throw()
    {
        var (samples, het, gbaf) = Simulate(M1);
        var male = OncologyAnalyzer.AscatSexModel.MaleWithXNonPar(OncologyAnalyzer.ReferenceGenome.GRCh37);
        var allHom = het.Select(_ => false).ToList();

        Assert.Multiple(() =>
        {
            Assert.Throws<ArgumentNullException>(() => _ = new OncologyAnalyzer.AscatMaleXGenotyping(null!, 1));
            Assert.Throws<ArgumentException>(() => _ = new OncologyAnalyzer.AscatMaleXGenotyping(male, 1, new[] { 0.5, 1.2 }));
