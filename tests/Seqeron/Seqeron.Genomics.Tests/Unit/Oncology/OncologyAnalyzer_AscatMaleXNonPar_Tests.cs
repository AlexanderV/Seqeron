                samples[0], het, new OncologyAnalyzer.AscatMaleXGenotyping(male, 1, gbaf.Take(10).ToList())));
            // sample(nonPAR_index, NA) fails in R when no autosomal probe is heterozygous.
            Assert.Throws<ArgumentException>(() => OncologyAnalyzer.SegmentAlleleSpecificAspcf(
                samples[0], allHom, new OncologyAnalyzer.AscatMaleXGenotyping(male, 1)));
        });
    }

