    /// <summary>
    /// Per probe: 3 MINSTD draws for the germline (ug, g1, g2), then per sample 9 draws (4 × logR noise, BAF orientation,
    /// 4 × BAF noise). Germline BAF: het 0.5 + 0.1·(g1 + g2 − 1); hom g1 &lt; 0.5 ? 0.05·g2 : 1 − 0.05·g2; hemizygous X as
    /// hom but exactly 0/1 when g2 &lt; 0.4. Genotype (ASCAT gg without ascat.gg) = germline BAF in [0.3, 0.7].
    /// </summary>
    private static (List<IReadOnlyList<OncologyAnalyzer.AlleleSpecificLocus>> Samples, List<bool> Het, List<double> Gbaf) Simulate(Track t)
    {
        double s = t.Seed;
        double U()
        {
            s = (s * 48271.0) % 2147483647.0;
            return s / 2147483647.0;
        }

        var samples = new List<List<OncologyAnalyzer.AlleleSpecificLocus>>();
        for (int k = 0; k < t.Samples; k++)
        {
            samples.Add(new List<OncologyAnalyzer.AlleleSpecificLocus>());
        }

        var het = new List<bool>();
        var gbaf = new List<double>();
        foreach (Block block in t.Blocks)
        {
            for (int p = 0; p < block.N; p++)
            {
                double ug = U(), g1 = U(), g2 = U();
                bool hom = block.Kind != 'A' || ug < t.PHom;
                double g = block.Kind == 'X'
                    ? (g1 < 0.5 ? (g2 < 0.4 ? 0.0 : 0.05 * g2) : (g2 < 0.4 ? 1.0 : 1.0 - 0.05 * g2))
                    : hom ? (g1 < 0.5 ? 0.05 * g2 : 1.0 - 0.05 * g2) : 0.5 + 0.1 * (g1 + g2 - 1.0);
                long position = block.Start + p * block.Step;
                for (int k = 0; k < t.Samples; k++)
                {
                    double a1 = U(), a2 = U(), a3 = U(), a4 = U(), us = U(), c1 = U(), c2 = U(), c3 = U(), c4 = U();
                    double x = block.R[k] + 0.2 * ((((a1 + a2) + a3) + a4) - 2.0);
                    double y;
                    if (hom && block.Kind != 'X')
                    {
                        y = us < 0.5 ? 0.0 : 1.0;
                    }
                    else
                    {
                        double b0 = us < 0.5 ? 1.0 - block.B[k] : block.B[k];
                        y = Math.Min(1.0, Math.Max(0.0, b0 + 0.1 * ((((c1 + c2) + c3) + c4) - 2.0)));
                    }

                    samples[k].Add(new OncologyAnalyzer.AlleleSpecificLocus(block.Chrom, position, x, y));
                }

                gbaf.Add(g);
                het.Add(!(g < 0.3 || g > 0.7));
            }
        }

        return (samples.Cast<IReadOnlyList<OncologyAnalyzer.AlleleSpecificLocus>>().ToList(), het, gbaf);
    }

    private static OncologyAnalyzer.AscatMaleXGenotyping MaleX(Track t, List<double> gbaf) =>
        new(OncologyAnalyzer.AscatSexModel.MaleWithXNonPar(OncologyAnalyzer.ReferenceGenome.GRCh37), t.RSeed, t.UseGermlineBaf ? gbaf : null);

    // asmultipcf cohorts run with penalty = 10 (raw joint cost), so the X non-PAR step and per-sample refinement show.
    private const double AsMultiPcfPenalty = 10.0;

    private static IReadOnlyList<OncologyAnalyzer.AspcfSegmentation> Run(Track t)
    {
        var (samples, het, gbaf) = Simulate(t);
        if (t.Samples == 1)
        {
            return new[] { OncologyAnalyzer.SegmentAlleleSpecificAspcf(samples[0], het, MaleX(t, gbaf)) };
        }

        return OncologyAnalyzer.SegmentAlleleSpecificAsMultiPcf(
            samples, het, AsMultiPcfPenalty, new OncologyAnalyzer.AsMultiPcfOptions { MaleXGenotyping = MaleX(t, gbaf) });
    }

    private static string SelectedBits(OncologyAnalyzer.AspcfSegmentation seg)
    {
        var bits = new System.Text.StringBuilder();
        for (int i = 0; i < seg.Loci.Count; i++)
        {
            var l = seg.Loci[i];
            if (l.Chromosome == "X" && l.Position >= XNonPar.Start && l.Position <= XNonPar.End)
            {
                bits.Append(seg.GermlineHeterozygous[i] ? '1' : '0');
            }
        }

        return bits.ToString();
    }

