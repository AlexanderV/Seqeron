    // S-MALEX-2 — with ≤ 5 known non-PAR probes ASCAT leaves the genotypes alone (length(nonPAR_index) > 5).
    [Test]
    public void MaleXNonParRegenotyping_FiveNonParProbes_Unchanged()
    {
        var loci = new List<OncologyAnalyzer.AlleleSpecificLocus>();
        var het = new List<bool>();
        for (int i = 0; i < 20; i++)
        {
            loci.Add(new("1", 1000 + i, 0.0, 0.5));
            het.Add(true);
        }

        for (int i = 0; i < 5; i++)
        {
            loci.Add(new("X", 5_000_000 + i, -0.5, 0.0));
            het.Add(false);
        }

        var spec = new OncologyAnalyzer.AscatMaleXGenotyping(OncologyAnalyzer.AscatSexModel.MaleWithXNonPar(OncologyAnalyzer.ReferenceGenome.GRCh37), 1);
        var result = OncologyAnalyzer.SegmentAlleleSpecificAspcf(loci, het, spec);
        Assert.That(result.GermlineHeterozygous, Is.EqualTo(het));
    }

