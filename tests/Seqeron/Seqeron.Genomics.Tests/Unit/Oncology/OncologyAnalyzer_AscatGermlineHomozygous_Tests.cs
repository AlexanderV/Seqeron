            int k = 0;
            foreach (var s in seg.Segments)
            {
                for (int j = 0; j < s.LocusCount; j++, k++)
                {
                    Assert.That(seg.SegmentedLogR[k], Is.EqualTo(s.MeanLogR), $"Locus {k + 1} carries its segment level.");
