            }
        });
    }

    // S-ASPCF-G2 — all heterozygous: the germline-aware overload reproduces the het-only overload bit for bit
    // (logR levels, BAF, extents), so existing callers keep their (R-verified, F13) behaviour.
    [TestCaseSource(nameof(ReferenceGenomes))]
    public void SegmentAlleleSpecificAspcf_AllHeterozygous_EqualsHetOnlyOverload(
