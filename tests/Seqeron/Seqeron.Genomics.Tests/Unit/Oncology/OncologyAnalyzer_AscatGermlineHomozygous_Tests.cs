            Assert.That(seg.Segments.Sum(s => s.LocusCount), Is.EqualTo(1080), "Segments tile all loci.");
            Assert.That(seg.Segments.Sum(s => s.HeterozygousLocusCount), Is.EqualTo(het.Count(h => h)), "608 heterozygous loci.");
            for (int i = 0; i < loci.Count; i++)
            {
                Assert.That(double.IsNaN(seg.SegmentedBaf[i]), Is.EqualTo(!het[i]), $"Locus {i + 1}: BAF only where heterozygous.");
