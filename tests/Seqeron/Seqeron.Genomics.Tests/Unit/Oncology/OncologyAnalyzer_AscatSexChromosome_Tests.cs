    // S-ASCAT-X4 — hand-computed haploid / diploid equations and the > 50 % non-PAR overlap rule. rho = 0.5, psi = 2,
    // gamma = 1, logR 0 ⇒ (1 − rho)·2 + rho·psi = 2: haploid nAraw = (0.5 − 1 + 2·2⁰)/0.5 = 3 ⇒ 3:0; diploid with
    // BAF 0.5: nA = nB = (0.5 − 1 + 0.5·2)/0.5 = 1 ⇒ 1:1. X segment [1, 10]: overlap with [6, 100] = 5/10 (not > 0.5)
    // ⇒ diploid; with [5, 100] = 6/10 ⇒ haploid; Y is haploid regardless of X_nonPAR; "chrX" is X.
    [Test]
    public void HaploidEquationAndNonParOverlapRule_HandComputed()
    {
        var summaries = new List<OncologyAnalyzer.AlleleSpecificSegmentSummary>
        {
            new("1", 1, 100, 0.0, 0.5, 10),
            new("X", 1, 10, 0.0, 0.5, 10),
            new("chrY", 1, 10, 0.0, 0.5, 10),
        };

        (int, int)[] Run(OncologyAnalyzer.AscatSexModel m) => OncologyAnalyzer.EvaluatePurityPloidy(summaries, m, 0.5, 2.0)
            .Segments.Select(s => (s.MajorCopyNumber, s.MinorCopyNumber)).ToArray();

        Assert.Multiple(() =>
        {
            Assert.That(Run(Female), Is.EqualTo(new[] { (1, 1), (1, 1), (1, 1) }), "XX: X and Y diploid.");
            Assert.That(Run(Male), Is.EqualTo(new[] { (1, 1), (3, 0), (3, 0) }), "XY, no X_nonPAR: X and Y haploid.");
            Assert.That(Run(new(OncologyAnalyzer.AscatGender.XY, (6L, 100L))), Is.EqualTo(new[] { (1, 1), (1, 1), (3, 0) }),
                "Overlap 5/10 = 0.5 is not > 0.5 ⇒ X segment diploid (PAR).");
            Assert.That(Run(new(OncologyAnalyzer.AscatGender.XY, (5L, 100L))), Is.EqualTo(new[] { (1, 1), (3, 0), (3, 0) }),
                "Overlap 6/10 > 0.5 ⇒ X segment haploid (non-PAR).");
            Assert.That(Run(new(OncologyAnalyzer.AscatGender.XY, (20L, 100L))), Is.EqualTo(new[] { (1, 1), (1, 1), (3, 0) }),
                "No overlap ⇒ diploid.");
            Assert.That(Run(new(OncologyAnalyzer.AscatGender.XX, (1L, 100L))), Is.EqualTo(new[] { (1, 1), (1, 1), (1, 1) }),
                "X_nonPAR is ignored for XX.");
            Assert.That(OncologyAnalyzer.EvaluatePurityPloidy(summaries, Male, 0.5, 2.0).Ploidy, Is.EqualTo(8.0 / 3.0),
                "Ploidy = probe-weighted mean total (2 + 3 + 3)/3.");
        });
    }

