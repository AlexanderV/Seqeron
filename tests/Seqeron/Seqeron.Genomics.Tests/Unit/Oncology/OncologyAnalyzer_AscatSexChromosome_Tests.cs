    /// <summary>
    /// Per probe: 10 MINSTD draws (genotype, 4 × logR noise, BAF orientation, 4 × BAF noise), exactly as the F36/F37
    /// generator; positions per <see cref="Block"/>.
    /// </summary>
    private static (List<OncologyAnalyzer.AlleleSpecificLocus> Loci, List<bool> Het) Simulate(Genome g)
    {
        double s = g.Seed;
        double U()
        {
            s = (s * 48271.0) % 2147483647.0;
            return s / 2147483647.0;
        }

        var loci = new List<OncologyAnalyzer.AlleleSpecificLocus>();
        var het = new List<bool>();
        foreach (Block block in g.Blocks)
        {
            for (int p = 0; p < block.N; p++)
            {
                double ug = U(), a1 = U(), a2 = U(), a3 = U(), a4 = U(), us = U(), c1 = U(), c2 = U(), c3 = U(), c4 = U();
                bool hom = block.ForceHom || ug < g.PHom;
                double x = block.R + 0.2 * ((((a1 + a2) + a3) + a4) - 2.0);
                double y;
                if (hom)
                {
                    y = us < 0.5 ? 0.0 : 1.0;
                }
                else
                {
                    double b0 = us < 0.5 ? 1.0 - block.B : block.B;
                    y = Math.Min(1.0, Math.Max(0.0, b0 + 0.1 * ((((c1 + c2) + c3) + c4) - 2.0)));
                }

                long pos = block.Pos0 < 0 ? (loci.Count + 1) * 1000L : block.Pos0 + p * block.Step;
                loci.Add(new OncologyAnalyzer.AlleleSpecificLocus(block.Chrom, pos, x, y));
                het.Add(!hom);
            }
        }

        return (loci, het);
    }

    private static OncologyAnalyzer.AspcfSegmentation Segment(Genome g)
    {
        var (loci, het) = Simulate(g);
        return OncologyAnalyzer.SegmentAlleleSpecificAspcf(loci, het, 70.0);
    }

    private static IReadOnlyList<OncologyAnalyzer.AlleleSpecificSegmentSummary> HetOnlySummaries(Genome g)
    {
        var (loci, het) = Simulate(g);
        return OncologyAnalyzer.SegmentAlleleSpecificAspcf(loci.Where((_, i) => het[i]), 70.0);
    }

