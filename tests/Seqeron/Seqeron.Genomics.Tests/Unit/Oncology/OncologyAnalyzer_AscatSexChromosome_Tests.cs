                {
                    Assert.That(male.Segments[i].MinorCopyNumber, Is.Zero, $"Segment {i + 1} ({chr}): haploid ⇒ nB = 0.");
                }
                else
                {
                    Assert.That(male.Segments[i], Is.EqualTo(female.Segments[i]), $"Segment {i + 1}: autosome unchanged.");
                }
            }
        });
    }

