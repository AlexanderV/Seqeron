    // S-ASCAT-X2 — the sex model never changes the fit (ASCAT: autoprobes = !(chr %in% sexchromosomes) for any gender):
    // purity, psi, GoF and the non-aberrant flag are identical; autosomal segments are identical; haploid X/Y segments
