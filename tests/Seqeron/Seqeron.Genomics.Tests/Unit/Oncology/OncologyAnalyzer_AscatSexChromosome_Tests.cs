    [TestCaseSource(nameof(Genomes))]
    public void MaleModel_ChangesOnlySexChromosomeSegments(Genome genome)
    {
        var seg = Segment(genome);
        var female = OncologyAnalyzer.FitPurityPloidyFromAspcf(seg, Female);
        var male = OncologyAnalyzer.FitPurityPloidyFromAspcf(seg, Male);

        Assert.Multiple(() =>
        {
            Assert.That((male.Purity, male.Psi, male.GoodnessOfFit, male.IsNonAberrant),
                Is.EqualTo((female.Purity, female.Psi, female.GoodnessOfFit, female.IsNonAberrant)));
            for (int i = 0; i < male.Segments.Count; i++)
            {
                string chr = male.Segments[i].Chromosome;
