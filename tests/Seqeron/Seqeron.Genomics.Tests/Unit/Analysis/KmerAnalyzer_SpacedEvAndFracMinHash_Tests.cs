    {
        double actual = KmerAnalyzer.SpacedWordDistance(
            SpacedSeqs.Value[first], SpacedSeqs.Value[second], Patterns[patterns], Metric(metric), AcgtOnly, both);
        if (double.IsNaN(printed))
        {
            Assert.That(actual, Is.NaN);
            return;
        }
        // Equal to the 12 printed significant digits: within one unit of the 12th digit (summation order may move the
        // last printed digit, e.g. D/E P6 JS both 0.4983603661055… prints …106 in C++ and …105 here).
        double unit = Math.Pow(10, Math.Floor(Math.Log10(Math.Abs(printed))) - 11);
        Assert.That(actual, Is.EqualTo(printed).Within(unit));
    }

    [Test]
    public void SpacedReader_GapInput_EqualsSpacedBinary_AndStrippedInput()
    {
        // tiny.fa  >X ACG-TACGT  >Y ACGTTACGA, patterns 1011/1101 (spaced binary, 12 digits):
        // JS -r 0.57013316426 (no -r 0.57013316426), EU -r 2.64575131106 / 4.69041575982, EV -r 0.427666596474 / 0.578620038162.
        // Before WP9 the gap was kept as an N window: JS -r 0.25.
        const string x = "ACG-TACGT", y = "ACGTTACGA";
        string[] p = Patterns["PT"];
        Assert.Multiple(() =>
        {
            Assert.That(Printed(KmerAnalyzer.SpacedWordDistance(x, y, p, KmerDistanceMetric.JensenShannon, AcgtOnly)), Is.EqualTo("0.57013316426"));
            Assert.That(Printed(KmerAnalyzer.SpacedWordDistance(x, y, p, KmerDistanceMetric.JensenShannon, AcgtOnly, true)), Is.EqualTo("0.57013316426"));
            Assert.That(Printed(KmerAnalyzer.SpacedWordDistance(x, y, p, KmerDistanceMetric.EuclideanCounts, AcgtOnly)), Is.EqualTo("2.64575131106"));
            Assert.That(Printed(KmerAnalyzer.SpacedWordDistance(x, y, p, KmerDistanceMetric.EuclideanCounts, AcgtOnly, true)), Is.EqualTo("4.69041575982"));
            Assert.That(Printed(KmerAnalyzer.SpacedWordDistance(x, y, p, KmerDistanceMetric.SpacedEvolutionary, AcgtOnly)), Is.EqualTo("0.427666596474"));
            Assert.That(Printed(KmerAnalyzer.SpacedWordDistance(x, y, p, KmerDistanceMetric.SpacedEvolutionary, AcgtOnly, true)), Is.EqualTo("0.578620038162"));
            // The reader deletes '-', '*', digits and blanks: identical to the stripped input.
            Assert.That(KmerAnalyzer.SpacedWordDistance("AC G-*7TACGT", y, p, KmerDistanceMetric.JensenShannon, AcgtOnly),
                Is.EqualTo(KmerAnalyzer.SpacedWordDistance("ACGTACGT", y, p, KmerDistanceMetric.JensenShannon, AcgtOnly)));
            // The literal default windows the string as given (a gap is a symbol), so it differs.
            Assert.That(KmerAnalyzer.SpacedWordDistance(x, y, p, KmerDistanceMetric.JensenShannon, KmerCountingOptions.Default),
                Is.Not.EqualTo(KmerAnalyzer.SpacedWordDistance(x, y, p, KmerDistanceMetric.JensenShannon, AcgtOnly)));
        });
    }

