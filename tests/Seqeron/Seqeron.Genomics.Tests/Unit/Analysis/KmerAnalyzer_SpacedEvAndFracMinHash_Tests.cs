    public void KmerDistance_SpacedEvolutionary_IsContiguousPattern()
    {
        var s = SpacedSeqs.Value;
        Assert.Multiple(() =>
        {
            foreach (bool both in new[] { false, true })
            {
                Assert.That(KmerAnalyzer.KmerDistance(s["A"], s["B"], 8, KmerDistanceMetric.SpacedEvolutionary, 0, both),
                    Is.EqualTo(KmerAnalyzer.SpacedWordDistance(s["A"], s["B"], ["11111111"], KmerDistanceMetric.SpacedEvolutionary, AcgtOnly, both)));
            }
            // spaced -f 11111111 -d EV on A/B: -r 0.119340289783, default (both strands) 0.122709335653.
            Assert.That(KmerAnalyzer.KmerDistance(s["A"], s["B"], 8, KmerDistanceMetric.SpacedEvolutionary), Is.EqualTo(0.119340289783).Within(1e-12));
            Assert.That(KmerAnalyzer.KmerDistance(s["A"], s["B"], 8, KmerDistanceMetric.SpacedEvolutionary, 0, bothStrands: true),
                Is.EqualTo(0.122709335653).Within(1e-12));
            // spaced -r -f pat3 (1111) on A/B saturates: 1.2.
            Assert.That(KmerAnalyzer.KmerDistance(s["A"], s["B"], 4, KmerDistanceMetric.SpacedEvolutionary), Is.EqualTo(1.2));
            Assert.Throws<ArgumentException>(() => KmerAnalyzer.KmerDistance(s["A"], s["B"], 4, KmerDistanceMetric.SpacedEvolutionary, 1));
        });
    }

