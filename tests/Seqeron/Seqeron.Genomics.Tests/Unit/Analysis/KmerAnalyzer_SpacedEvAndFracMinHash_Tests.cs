    private static string Mutate(string s, ulong seed, int percent)
    {
        _x = seed;
        var c = s.ToCharArray();
        for (int i = 0; i < c.Length; i++)
        {
            ulong r = Next();
            if ((r >> 33) % 100 < (ulong)percent)
                c[i] = "ACGT"[(int)(((ulong)"ACGT".IndexOf(c[i]) + 1 + (r >> 40) % 3) % 4)];
        }
        return new string(c);
    }

    // gen2.py dirty(): gaps '-', '*', digits inserted; N / R substituted; every 5th symbol lower-cased.
    private static string Dirty(string s)
    {
        var sb = new System.Text.StringBuilder();
        for (int i = 0; i < s.Length; i++)
        {
            char ch = s[i];
            if (i % 53 == 0) sb.Append('-');
            if (i % 71 == 0) sb.Append('*');
            if (i % 97 == 0) sb.Append('7');
            if (i % 89 == 0) ch = 'N';
            else if (i % 113 == 0) ch = 'R';
            if (i % 5 == 0) ch = char.ToLowerInvariant(ch);
            sb.Append(ch);
        }
        return sb.ToString();
    }

