            Assert.That(Assert.Throws<ArgumentOutOfRangeException>(() => KmerAnalyzer.MashPValue(1, 1000, 1000, 33, 10))!.ParamName, Is.EqualTo("k"));
            Assert.That(Assert.Throws<ArgumentOutOfRangeException>(() => KmerAnalyzer.MashPValue(1, 1000, 1000, 0, 10))!.ParamName, Is.EqualTo("k"));
            // k = 32: r = 2.710505431213761e-17, scipy binom.sf(0, 10, r) = 2.7105054312137606e-16.
            Assert.That(KmerAnalyzer.MashPValue(1, 1000, 1000, 32, 10), Is.EqualTo(2.7105054312137606e-16).Within(1e-12).Percent);
        });
    }

