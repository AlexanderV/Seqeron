    #region Deterministic sequences (LCG, identical to gen.py)

    private sealed class Lcg(ulong seed)
    {
        private ulong _x = seed;
        public ulong Next()
        {
            _x = unchecked(_x * 6364136223846793005UL + 1442695040888963407UL);
            return _x >> 33;
        }
    }

    private static string Dna(int n, ulong seed)
    {
        var g = new Lcg(seed);
        var sb = new StringBuilder(n);
        for (int i = 0; i < n; i++)
            sb.Append("ACGT"[(int)((g.Next() >> 29) & 3)]);
        return sb.ToString();
    }

    private static string Mutate(string seq, int perMille, ulong seed)
    {
        var g = new Lcg(seed);
        var sb = new StringBuilder(seq.Length);
        foreach (char c in seq)
        {
            if (g.Next() % 1000 < (ulong)perMille)
                sb.Append("ACGT"[("ACGT".IndexOf(c) + 1 + (int)(g.Next() % 3)) % 4]);
            else
                sb.Append(c);
        }
        return sb.ToString();
    }

    private static readonly string A = Dna(10000, 1);
    private static readonly string B = Mutate(A, 10, 2);   // ~1 % substitutions (near-identical)
    private static readonly string C = Mutate(A, 50, 3);   // ~5 % substitutions
    private static readonly string D = Dna(10000, 4);      // unrelated
    private static readonly string E = Lower5kWithN();     // A[2000..7000) lower-case + "NNNNN" (contained in A)
    private static readonly string[] AA2 = [A[..6000], A[6000..]]; // A split into two FASTA records

    private static string Lower5kWithN()
    {
        var e = A[2000..7000].ToLowerInvariant();
        return e[..1000] + "NNNNN" + e[1000..];
    }

    private static IEnumerable<string> Records(string name) => name switch
    {
        "A" => [A], "B" => [B], "C" => [C], "D" => [D], "E" => [E], "AA2" => AA2,
        _ => throw new ArgumentException(name),
    };

