    [Test]
    public void ContainmentIndex_IdentityAndConventions()
    {
        var opt = new KmerCountingOptions(Canonical: true);
        int nA = KmerAnalyzer.DistinctKmers(A, 21, opt).Count;
        int nB = KmerAnalyzer.DistinctKmers(B, 21, opt).Count;
        double cab = KmerAnalyzer.ContainmentIndex(A, B, 21, opt);
        double cba = KmerAnalyzer.ContainmentIndex(B, A, 21, opt);
        double j = KmerAnalyzer.JaccardSimilarity(A, B, 21, opt);
        Assert.Multiple(() =>
        {
            Assert.That(cab * nA, Is.EqualTo(cba * nB).Within(1e-9), "C(A,B)|A| = C(B,A)|B| = |A∩B|");
            Assert.That(Math.Round(cab * nA), Is.EqualTo(8069), "mash dist -s 100000 shared");
            Assert.That(j, Is.LessThanOrEqualTo(Math.Min(cab, cba)));
            // literal: GATTACA k=3 {GAT, ATT, TTA, TAC, ACA} in GATTACCA {GAT, ATT, TTA, TAC, ACC, CCA} → 4/5.
            Assert.That(KmerAnalyzer.ContainmentIndex("GATTACA", "GATTACCA", 3), Is.EqualTo(0.8));
            Assert.That(KmerAnalyzer.ContainmentIndex("", "ACGT", 2), Is.EqualTo(0.0));
            Assert.That(KmerAnalyzer.ContainmentIndex(null!, null!, 2), Is.EqualTo(0.0));
            Assert.Throws<ArgumentOutOfRangeException>(() => KmerAnalyzer.ContainmentIndex("ACGT", "ACGT", 0));
        });
