    /// <summary>C++ ostream default formatting (precision 6, %g) of a double.</summary>
    private static string Cpp(double v) => v.ToString("G6", CultureInfo.InvariantCulture).ToLowerInvariant();

    [TestCaseSource(nameof(MashDistCases))]
    public void CompareMinHashSketches_EqualsMashDistOutput(
        string reference, string query, int k, int s, bool canonical, string distance, string pValue, int x, int denom)
    {
        var r = KmerAnalyzer.CreateMinHashSketch(Records(reference), k, s, canonical);
        var q = KmerAnalyzer.CreateMinHashSketch(Records(query), k, s, canonical);
        var result = KmerAnalyzer.CompareMinHashSketches(r, q);
        Assert.Multiple(() =>
        {
            Assert.That(result.SharedHashes, Is.EqualTo(x), "x");
            Assert.That(result.Denominator, Is.EqualTo(denom), "s");
            Assert.That(result.Jaccard, Is.EqualTo((double)x / denom), "J");
            Assert.That(Cpp(result.Distance), Is.EqualTo(distance), "distance");
            Assert.That(Cpp(result.PValue), Is.EqualTo(pValue), "p-value");
        });
    }

    [Test]
    public void SketchLargerThanUnion_EqualsExactJaccardAndMashDistance()
    {
        // mash dist -s 100000 (s ≥ |union|) is the exact canonical Jaccard: 8069/11891 = sourmash scaled=1 jaccard
        // 0.678580438987470.
        var opt = new KmerCountingOptions(Canonical: true);
        var cmp = KmerAnalyzer.CompareMinHashSketches(
            KmerAnalyzer.CreateMinHashSketch(A, 21, 100000), KmerAnalyzer.CreateMinHashSketch(B, 21, 100000));
        Assert.Multiple(() =>
        {
            Assert.That(cmp.Jaccard, Is.EqualTo(KmerAnalyzer.JaccardSimilarity(A, B, 21, opt)));
            Assert.That(cmp.Jaccard, Is.EqualTo(0.678580438987470).Within(1e-14));
            Assert.That(cmp.Distance, Is.EqualTo(KmerAnalyzer.MashDistance(A, B, 21, opt)));
        });
    }

