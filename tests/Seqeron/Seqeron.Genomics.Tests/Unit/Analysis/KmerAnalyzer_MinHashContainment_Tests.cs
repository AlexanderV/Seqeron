// KMER-DIST-001 (audit round 2, WP7) — Mash bottom-s MinHash sketches (MurmurHash3_x64_128, seed 42, 32-bit hashes
// for k ≤ 16), sketch comparison (x/s, Jaccard estimate, Mash distance, binomial p-value) and the exact containment
// index C(A, B) = |K(A) ∩ K(B)| / |K(A)|.
// Evidence: docs/Evidence/KMER-DIST-001-Evidence.md; TestSpecs: KMER-DIST-001.md §4.7; algorithm doc §7.6.
// Sources: Ondov et al. 2016 (Genome Biol 17:132); Mash v2.3 src/mash/Sketch.cpp (addMinHashes, use64 = 4^k > 2^32,
//          sketchFile: records shorter than k skipped, length = Σ record lengths), hash.cpp (h1 / low 32 bits),
//          MinHashHeap.cpp (non-redundant bottom-s), CommandDistance.cpp (compareSketches, pValue =
//          gsl_cdf_binomial_Q(x − 1, r, denom)), MurmurHash3.cpp; Koslicki & Zabeti 2019 (Appl Math Comput 354:206).
// Reference values (executed):
//   - the Mash 2.3 binary (`mash dist -k K -s S [-n] ref.fa qry.fa`, `mash info -d`), printed with C++ default
//     precision (6 significant digits) — compared here as strings after formatting with "G6";
//   - sourmash 4.9.4 (MinHash(n=1000, ksize=21) = the Mash hash set; MinHash(scaled=1).contained_by / jaccard);
//   - mmh3 5.x (mmh3.hash64(key, 42, signed=False)) for MurmurHash3_x64_128.
// The sequences are generated by the 64-bit LCG below; the same generator in Python (gen.py, Evidence) wrote the
// FASTA files given to Mash and sourmash.

