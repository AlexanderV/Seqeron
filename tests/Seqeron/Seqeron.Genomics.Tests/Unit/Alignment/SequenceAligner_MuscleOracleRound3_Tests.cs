using NUnit.Framework;
using Seqeron.Genomics.Alignment;
using R2 = Seqeron.Genomics.Tests.Unit.Alignment.SequenceAligner_MuscleOracleRound2_Tests;

namespace Seqeron.Genomics.Tests.Unit.Alignment;

/// <summary>
/// ALIGN-MULTI-001 (audit A2-1 = A1-10c part a3, B09 F89): round-3 oracle of MUSCLE v3.8.1551 - 60 sets that round 2 could not record or never exercised: the 8 sets of
/// <c>-matrix blosum62nostar</c> (R330 ... R350, the program's "Matrix is not symmetrical" warning prints the byte 0xff), <c>-matrix</c> with DNA / RNA (R638 ... R645), one- and two-sequence
/// profiles / trees / scores / refinements / alignments (R646 ... R681) and the score flags <c>-le -sp -sv -spn</c> on nucleotides and proteins (R682 ... R689).
/// Generated by scripts/alignment/generate_muscle3_r3_oracle.py from the unmodified Debian muscle3 3.8.1551 binary (apt package muscle3, run locally: <c>handoff/A1-10c-muscle-r3/returned/ENV-local.txt</c>)
/// through the package's own harness run_sets.py. Every set must give MUSCLE's rows in MUSCLE's written order, files and printed scores - or, where the program refuses (10 runs: 8 segmentation
/// faults, 2 "Clust::SetLeafCount(1)"), the matching refusal of the port.
/// </summary>
[TestFixture]
[Category("Alignment")]
[Category("ALIGN-MULTI-001")]
public class SequenceAligner_MuscleOracleRound3_Tests
{
    private static readonly Lazy<List<R2.Row>> Oracle = new(() => R2.Load("muscle3_r3_oracle.tsv"));

    public static IEnumerable<TestCaseData> AlignSets() => Oracle.Value.Where(r => r.Kind == "align").Select(r => new TestCaseData(r.Id).SetArgDisplayNames(r.Id));

    public static IEnumerable<TestCaseData> ModeSets() => Oracle.Value.Where(r => r.Kind != "align").Select(r => new TestCaseData(r.Id).SetArgDisplayNames(r.Id));

    [Test]
    public void Oracle_Has60Sets_TheIdsOfThePackage()
    {
        // R330, R335, R336, R342, R344, R347, R348, R350 (the round-2 gap) + R638 ... R689
        var expected = new[] { "R330", "R335", "R336", "R342", "R344", "R347", "R348", "R350" }.Concat(Enumerable.Range(638, 52).Select(i => "R" + i)).ToHashSet();
        Assert.Multiple(() =>
        {
            Assert.That(Oracle.Value, Has.Count.EqualTo(60));
            Assert.That(Oracle.Value.Select(r => r.Id).ToHashSet(), Is.EquivalentTo(expected));
            Assert.That(Oracle.Value.Count(r => r.Kind == "align"), Is.EqualTo(37));
            Assert.That(Oracle.Value.Count(r => r.Rc != "0"), Is.EqualTo(10), "the program refuses 10 of the 60 sets");
        });
    }

    [Test]
    public void TheEightRoundTwoGapIdsAreNowInTheRound3Oracle()
    {
        var round2 = R2.Oracle.Value.Select(r => r.Id).ToHashSet();
        var round3 = Oracle.Value.Select(r => r.Id).ToHashSet();
        Assert.Multiple(() =>
        {
            Assert.That(Enumerable.Range(0, 638).Select(i => "R" + i).Except(round2).Except(round3), Is.Empty, "R0 ... R637 are covered by round 2 + round 3");
            Assert.That(round2.Intersect(round3), Is.Empty, "no set is in both oracles");
        });
    }

    [TestCaseSource(nameof(AlignSets))]
    public void Align_RowsWrittenOrderAndFiles_EqualMuscle3(string id) => R2.CheckAlign(Oracle.Value.First(x => x.Id == id));

    [TestCaseSource(nameof(ModeSets))]
    public void CommandLine_EqualsMuscle3(string id) => R2.CheckCommandLine(Oracle.Value.First(x => x.Id == id));
}
