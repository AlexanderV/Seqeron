"""Generate the Biopython 1.88 oracle for nucleotide 'X' in translation (B02 F33, TRANS-PROT-001).

Usage: python3 -I gen_biopython_nucleotide_x.py > biopython_nucleotide_x.tsv
Deterministic (random.Random(20261014)).
"""
import itertools
import random
import warnings

import Bio
from Bio.Data import CodonTable
from Bio.Seq import Seq

warnings.simplefilter("ignore")
ALPHA = "ACGTRYSWKMBDHVNX"
IDS = sorted(CodonTable.ambiguous_generic_by_id)


def tr(s, table, to_stop=False):
    try:
        return str(Seq(s).translate(table=table, to_stop=to_stop))
    except Exception:  # TranslationError / ValueError (to_stop on dual-coding tables)
        return "!"


x_codons = ["".join(c) for c in itertools.product(ALPHA, repeat=3) if "X" in "".join(c)]
print(f"# Generated by Biopython {Bio.__version__} (Bio.Seq.translate, Bio.Data.CodonTable.ambiguous_dna_by_id).")
print("# Section C: codon order = itertools.product('ACGTRYSWKMBDHVNX', repeat=3) filtered to codons containing X"
      f" ({len(x_codons)} per table). Columns: C, table_id, translation ('!' = TranslationError),"
      " X-containing ambiguous start codons, X-containing ambiguous stop codons ('-' = none).")
print("# Section R: random strings (DNA or RNA spelling, mixed case, with X). Columns: R, table_id, to_stop (0/1),"
      " input, Biopython output ('!' = error).")
for t in IDS:
    trans = "".join(tr(c, t) if len(tr(c, t)) == 1 else "?" for c in x_codons)
    # RNA spelling must give the same answers (ambiguous_rna_values['X'] == 'GAUC').
    assert trans == "".join(tr(c.replace("T", "U"), t) for c in x_codons)
    amb = CodonTable.ambiguous_dna_by_id[t]
    starts = sorted(c for c in amb.start_codons if "X" in c) or ["-"]
    stops = sorted(c for c in amb.stop_codons if "X" in c) or ["-"]
    print(f"C\t{t}\t{trans}\t{','.join(starts)}\t{','.join(stops)}")

rng = random.Random(20261014)
letters = "ACGTNRYXXXX"
for i in range(600):
    t = rng.choice(IDS)
    n = rng.randint(0, 40)
    s = "".join(rng.choice(letters) for _ in range(n))
    # bias towards plain codons so that many strings translate fully
    if rng.random() < 0.5:
        s = "".join(rng.choice("ACGTX" if rng.random() < 0.3 else "ACGT") for _ in range(n))
    if rng.random() < 0.3:
        s = s.replace("T", "U")
    if rng.random() < 0.4:
        s = "".join(ch.lower() if rng.random() < 0.5 else ch for ch in s)
    to_stop = rng.random() < 0.5
    print(f"R\t{t}\t{int(to_stop)}\t{s}\t{tr(s, t, to_stop)}")
