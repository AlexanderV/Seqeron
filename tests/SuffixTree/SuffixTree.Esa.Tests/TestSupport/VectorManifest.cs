using System.Globalization;

namespace SuffixTree.Esa.Tests.TestSupport;

/// <summary>
/// Reader of <c>analysis/sa_vectors.tsv</c>, the libsais reference vectors of work package 1a.6: tab-separated, <c>#</c> comment lines,
/// one header line, then <c>corpus kind n width sa_sha256 lcp_sha256</c> (definitions in the comment block of the file).
/// </summary>
public sealed class VectorManifest
{
    /// <summary>The seed passed to <see cref="StringFamilies.Adversarial"/> for the generated corpora.</summary>
    public const ulong GeneratedSeed = 1;

    /// <summary>The sizes of the generated adversarial corpora.</summary>
    public static readonly int[] GeneratedSizes = [100_000, 1_000_000];

    /// <summary>Corpus kind: a benchmark input file or an adversarial family generated by <see cref="StringFamilies"/>.</summary>
    public enum CorpusKind
    {
        /// <summary>A benchmark input <c>data/&lt;corpus&gt;.txt</c> (outside the repository).</summary>
        File,

        /// <summary>A family of <see cref="StringFamilies.Adversarial"/>.</summary>
        Generated,
    }

    /// <summary>One manifest row.</summary>
    public sealed record Entry(string Corpus, CorpusKind Kind, int N, string Width, string SaSha256, string LcpSha256);

    private VectorManifest(List<Entry> entries) => Entries = entries;

    /// <summary>The rows in file order.</summary>
    public IReadOnlyList<Entry> Entries { get; }

    /// <summary>Path of <c>analysis/sa_vectors.tsv</c>.</summary>
    public static string DefaultPath() =>
        Path.Combine(CorpusManifest.BenchDirectory(), "..", "sa_vectors.tsv");

    /// <summary>Loads the committed manifest.</summary>
    public static VectorManifest Load() => Parse(File.ReadAllText(DefaultPath()));

    /// <summary>Parses manifest text; throws <see cref="FormatException"/> for a malformed row, a bad hash or a duplicate corpus.</summary>
    public static VectorManifest Parse(string text)
    {
        ArgumentNullException.ThrowIfNull(text);
        var entries = new List<Entry>();
        var seen = new HashSet<string>(StringComparer.Ordinal);
        bool header = false;
        int lineNo = 0;
        foreach (string raw in text.Split('\n'))
        {
            lineNo++;
            string line = raw.TrimEnd('\r');
            if (line.Trim().Length == 0 || line.StartsWith('#')) continue;
            string[] f = line.Split('\t');
            if (f.Length != 6) throw new FormatException($"sa_vectors line {lineNo}: expected 6 tab-separated fields, got {f.Length}");
            if (!header)
            {
                if (f[0] != "corpus") throw new FormatException($"sa_vectors line {lineNo}: header line expected");
                header = true;
                continue;
            }
            CorpusKind kind = f[1] switch
            {
                "file" => CorpusKind.File,
                "generated" => CorpusKind.Generated,
                _ => throw new FormatException($"sa_vectors line {lineNo}: unknown kind '{f[1]}'"),
            };
            if (!int.TryParse(f[2], NumberStyles.None, CultureInfo.InvariantCulture, out int n))
                throw new FormatException($"sa_vectors line {lineNo}: bad n '{f[2]}'");
            if (f[3] is not ("u8" or "u16")) throw new FormatException($"sa_vectors line {lineNo}: width must be u8 or u16");
            if (!IsSha256(f[4]) || !IsSha256(f[5])) throw new FormatException($"sa_vectors line {lineNo}: bad SHA-256");
            if (!seen.Add(f[0])) throw new FormatException($"sa_vectors line {lineNo}: duplicate corpus '{f[0]}'");
            entries.Add(new Entry(f[0], kind, n, f[3], f[4], f[5]));
        }
        if (!header) throw new FormatException("sa_vectors: header line missing");
        return new VectorManifest(entries);
    }

    /// <summary>Looks a row up by corpus name; throws <see cref="KeyNotFoundException"/> when absent.</summary>
    public Entry this[string corpus] => Entries.First(e => e.Corpus == corpus);

    /// <summary>The corpus name of a generated family: <c>&lt;family name&gt;-n&lt;N&gt;</c>.</summary>
    public static string GeneratedName(string family, int n) => $"{family}-n{n}";

    /// <summary>
    /// The generated corpora the manifest must contain: every <see cref="StringFamilies.Adversarial"/> family at each of
    /// <see cref="GeneratedSizes"/>, plus the all-distinct family at n = 65,536 (it needs sigma = n &lt;= 65,536 and so is absent above that).
    /// </summary>
    public static IEnumerable<(string Name, int N)> ExpectedGenerated()
    {
        foreach (int n in GeneratedSizes)
            foreach (var (name, _) in StringFamilies.Adversarial(n, GeneratedSeed))
                yield return (GeneratedName(name, n), n);
        yield return (GeneratedName($"all-distinct-s{GeneratedSeed}", 65_536), 65_536);
    }

    /// <summary>The file corpora (benchmark inputs) the manifest must contain, with their sizes.</summary>
    public static readonly (string Name, int N)[] ExpectedFiles =
    [
        ("dna_1m", 1_000_000), ("dna_10m", 10_000_000), ("rep_10m", 10_000_000), ("prot_1m", 1_000_000),
    ];

    /// <summary>Generates the text of a generated corpus by name (stops the family iterator at the match).</summary>
    public static string GenerateText(string corpus, int n)
    {
        string suffix = $"-n{n}";
        if (!corpus.EndsWith(suffix, StringComparison.Ordinal)) throw new ArgumentException($"'{corpus}' does not end with '{suffix}'", nameof(corpus));
        string family = corpus.Substring(0, corpus.Length - suffix.Length);
        foreach (var (name, text) in StringFamilies.Adversarial(n, GeneratedSeed))
            if (name == family) return text;
        if (n <= 65_536 && family == $"all-distinct-s{GeneratedSeed}") return StringFamilies.AllDistinct(n, GeneratedSeed);
        throw new KeyNotFoundException($"no adversarial family '{family}' at n = {n}");
    }

    private static bool IsSha256(string s)
    {
        if (s.Length != 64) return false;
        foreach (char c in s)
            if (!(c is >= '0' and <= '9' or >= 'a' and <= 'f')) return false;
        return true;
    }
}
