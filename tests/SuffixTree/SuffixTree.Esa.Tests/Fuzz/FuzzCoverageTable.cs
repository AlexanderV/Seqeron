using System.Text;
using SuffixTree.Esa.Tests.TestSupport;

namespace SuffixTree.Esa.Tests.Fuzz;

/// <summary>
/// The committed operation coverage list of the harness (<c>docs/refactoring/suffix-tree-upgrade/analysis/s1b/harness_member_coverage.tsv</c>, work package 1b.8; it replaces <c>facade_member_coverage.tsv</c> of 1b.6, which listed only
/// the hand-written tests of the facade): one row per member key of <see cref="FuzzMemberKeys"/> with the calls that the smoke slice of the harness made on the in-memory and on the file-backed engines and the harness steps that
/// made them. A reflection test fails when a member has no row (a new member cannot be forgotten) or a row names no member (a removed one is not left behind); an explicit test regenerates the table.
/// </summary>
internal static class FuzzCoverageTable
{
    internal const string Header = "key\tin_memory_calls\tfile_backed_calls\tharness_steps";

    /// <summary>Path of the committed table.</summary>
    internal static string DefaultPath() =>
        Path.Combine(CorpusManifest.RepositoryRoot(), "docs", "refactoring", "suffix-tree-upgrade", "analysis", "s1b", "harness_member_coverage.tsv");

    /// <summary>The keys of the rows of a table (the first column of every line that is not the header, blank or a comment).</summary>
    internal static List<string> Keys(string table) =>
        [.. table.Split('\n').Select(l => l.TrimEnd('\r')).Where(l => l.Length > 0 && !l.StartsWith('#') && !l.StartsWith("key\t", StringComparison.Ordinal)).Select(l => l.Split('\t')[0])];

    /// <summary>The rows of a table with their steps column (the first of two rows of one key).</summary>
    internal static Dictionary<string, string[]> Rows(string table)
    {
        var rows = new Dictionary<string, string[]>(StringComparer.Ordinal);
        foreach (string[] f in table.Split('\n').Select(l => l.TrimEnd('\r')).Where(l => l.Length > 0 && !l.StartsWith('#') && !l.StartsWith("key\t", StringComparison.Ordinal)).Select(l => l.Split('\t')))
            rows.TryAdd(f[0], f.Length > 3 ? f[3].Split(';', StringSplitOptions.RemoveEmptyEntries) : []);
        return rows;
    }

    /// <summary>The problems of a table against the members of the audited types: a member without a row, a row without a member, a duplicate row, a row that names no harness step.</summary>
    internal static List<string> Problems(string table)
    {
        var problems = new List<string>();
        List<string> keys = Keys(table);
        var rows = new HashSet<string>(keys, StringComparer.Ordinal);
        foreach (string duplicate in keys.GroupBy(k => k).Where(g => g.Count() > 1).Select(g => g.Key)) problems.Add($"duplicate row for {duplicate}");
        foreach (string member in FuzzMemberKeys.All.Where(m => !rows.Contains(m))) problems.Add($"no row for the member {member}");
        foreach (string row in keys.Where(k => !FuzzMemberKeys.All.Contains(k))) problems.Add($"the row {row} names no member of the audited types");
        foreach ((string key, string[] steps) in Rows(table))
        {
            if (steps.Length == 0) problems.Add($"the row {key} names no harness step");
            foreach (string step in steps.Where(s => !FuzzSteps.All.Contains(s))) problems.Add($"the row {key} names the unknown step {step}");
        }
        return problems;
    }

    /// <summary>The table of a run's counters. The in-memory column adds the calls of the engines named <c>memory-*</c>, the file-backed column those of <c>file-*</c>.</summary>
    internal static string Render(MemberCounters counters)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# The operation coverage list of the full differential fuzz (work package 1b.8): every public member of the interfaces ISuffixTreeSearch, ISuffixTreeAnalysis, ISuffixTreeDiagnostics, ISuffixTree,");
        sb.AppendLine("# the contract interfaces ISuffixIndex, ISuffixTreeNavigation, ISuffixArrayAccess, IIndexText, what a tree returns (ITextSource), the visitor of Traverse (ISuffixTreeVisitor), IDisposable, and the entry points");
        sb.AppendLine("# of the factories and of EsaOpenOptions that open a file-backed tree (SuffixIndexFactory.Open, EsaSuffixTreeFactory.Open / Create / CreateEsa, EsaOpenOptions). Generated by the explicit test");
        sb.AppendLine("# FullFuzzCoverageTableTests.RegenerateTheCommittedTable from the types by reflection and from a smoke slice of the harness (the counts are of that slice, not of the 30-minute run); a reflection test fails");
        sb.AppendLine("# when a member has no row or a row names no member. Steps: the classes of the harness that call the member (FuzzSteps).");
        sb.AppendLine(Header);
        foreach (string key in FuzzMemberKeys.All)
        {
            long memory = 0, file = 0;
            for (int e = 0; e < counters.Engines.Count; e++)
            {
                if (counters.Engines[e].StartsWith("memory", StringComparison.Ordinal)) memory += counters.Calls(e, key);
                else file += counters.Calls(e, key);
            }
            sb.Append(key).Append('\t').Append(memory).Append('\t').Append(file).Append('\t').AppendLine(string.Join(";", counters.StepsOf(key)));
        }
        return sb.ToString();
    }
}
