using System.Globalization;

namespace Seqeron.Genomics.MolTools;

/// <summary>
/// Which enzyme table a "list every enzyme" member of <see cref="RestrictionAnalyzer"/> draws from.
/// </summary>
/// <remarks>
/// Name lookups (<see cref="RestrictionAnalyzer.GetEnzyme"/> and every member that takes an enzyme
/// <i>name</i>) always resolve against the full <see cref="Rebase"/> set; the set only matters for the
/// members that enumerate a table.
/// </remarks>
public enum EnzymeSet
{
    /// <summary>
    /// The 39 hand-curated common laboratory enzymes of <see cref="RestrictionAnalyzer.Enzymes"/> —
    /// the default for every member that enumerates enzymes without being told which.
    /// </summary>
    Common = 0,

    /// <summary>
    /// Every REBASE enzyme with a defined cut in Biopython 1.88's REBASE 404 snapshot
    /// (<see cref="RestrictionAnalyzer.RebaseEnzymes"/>, 754 enzymes), the 39 common ones included.
    /// </summary>
    Rebase = 1,
}

public static partial class RestrictionAnalyzer
{
    #region REBASE Enzyme Set

    private const string RebaseResourceName = "Seqeron.Genomics.MolTools.Resources.rebase_enzymes.tsv";

    private static readonly Lazy<IReadOnlyDictionary<string, RestrictionEnzyme>> _rebaseEnzymes =
        new(LoadRebaseEnzymes, LazyThreadSafetyMode.ExecutionAndPublication);

    /// <summary>
    /// Every REBASE restriction enzyme with a defined cut position: 754 enzymes (729 cutting once per
    /// site, 25 cutting on both sides — <see cref="RestrictionEnzyme.SecondCut"/>), keyed
    /// case-insensitively by REBASE name, in the table's (case-insensitive alphabetical) order.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>Source.</b> Generated by <c>scripts/rebase/generate_rebase_enzymes.py</c> into the embedded
    /// resource <c>Resources/rebase_enzymes.tsv</c> (inputs pinned by sha256). Recognition site and cut
    /// offsets come from Biopython 1.88 <c>Bio/Restriction/Restriction_Dictionary.py</c> ("Used REBASE
    /// emboss files version 404 (2024)"): <see cref="RestrictionEnzyme.CutPositionForward"/> =
    /// <c>fst5</c>, <see cref="RestrictionEnzyme.CutPositionReverse"/> = <c>size + fst3</c>,
    /// <see cref="RestrictionEnzyme.SecondCut"/> = <c>(scd5, size + scd3)</c>. Organism (field
    /// <c>&lt;3&gt;</c>, verbatim, strain included) and the cognate-methylation field
    /// (<c>&lt;6&gt;</c>) come from REBASE <c>allenz.104</c>, joined by name; 7 enzymes absent from
    /// <c>allenz.104</c> (BscXI, CviKI_1, EcoO157SI, KroNI, PaqCI, TagI, UpaP162I) have both empty.
    /// </para>
    /// <para>
    /// <b>Excluded:</b> the 334 snapshot enzymes whose cut position REBASE does not define (Biopython
    /// <c>NoCut</c>/<c>NotDefined</c>, <c>fst5 is None</c>). A <see cref="RestrictionEnzyme"/> must
    /// carry integer cut offsets, and such an enzyme cannot be digested; inventing offsets would make
    /// every derived fragment a false statement.
    /// </para>
    /// <para>
    /// <b>The 39 common enzymes</b> are the very instances of <see cref="Enzymes"/> (their organism
    /// strings are the curated genus + species, not REBASE's strain-qualified form), so every result
    /// computed with them is unchanged.
    /// </para>
    /// </remarks>
    public static IReadOnlyDictionary<string, RestrictionEnzyme> RebaseEnzymes => _rebaseEnzymes.Value;

    /// <summary>
    /// Gets the enzyme table for <paramref name="set"/>: <see cref="Enzymes"/> for
    /// <see cref="EnzymeSet.Common"/>, <see cref="RebaseEnzymes"/> for <see cref="EnzymeSet.Rebase"/>.
    /// </summary>
    /// <exception cref="ArgumentOutOfRangeException"><paramref name="set"/> is not a defined value.</exception>
    public static IReadOnlyDictionary<string, RestrictionEnzyme> GetEnzymes(EnzymeSet set) => set switch
    {
        EnzymeSet.Common => _enzymes,
        EnzymeSet.Rebase => RebaseEnzymes,
        _ => throw new ArgumentOutOfRangeException(nameof(set), set, "Unknown enzyme set."),
    };

    /// <summary>Gets the enzymes of <paramref name="set"/> whose recognition string has exactly
    /// <paramref name="length"/> characters (see <see cref="GetEnzymesByCutLength(int)"/>).</summary>
    public static IEnumerable<RestrictionEnzyme> GetEnzymesByCutLength(int length, EnzymeSet set) =>
        GetEnzymes(set).Values.Where(e => e.RecognitionSequence.Length == length);

    /// <summary>Gets the enzymes of <paramref name="set"/> whose recognition-string length lies in
    /// [<paramref name="minLength"/>, <paramref name="maxLength"/>]
    /// (see <see cref="GetEnzymesByCutLength(int, int)"/>).</summary>
    public static IEnumerable<RestrictionEnzyme> GetEnzymesByCutLength(int minLength, int maxLength, EnzymeSet set) =>
        GetEnzymes(set).Values.Where(e =>
            e.RecognitionSequence.Length >= minLength &&
            e.RecognitionSequence.Length <= maxLength);

    /// <summary>Gets the blunt cutters of <paramref name="set"/> (see <see cref="GetBluntCutters()"/>).</summary>
    public static IEnumerable<RestrictionEnzyme> GetBluntCutters(EnzymeSet set) =>
        GetEnzymes(set).Values.Where(e => e.IsBluntEnd);

    /// <summary>Gets the sticky-end cutters of <paramref name="set"/> (see <see cref="GetStickyCutters()"/>).</summary>
    public static IEnumerable<RestrictionEnzyme> GetStickyCutters(EnzymeSet set) =>
        GetEnzymes(set).Values.Where(e => !e.IsBluntEnd);

    /// <summary>
    /// Finds all sites of every enzyme of <paramref name="set"/> in a molecule of the given topology
    /// (see <see cref="FindAllSites(DnaSequence, MoleculeTopology)"/>).
    /// </summary>
    public static IEnumerable<RestrictionSite> FindAllSites(
        DnaSequence sequence, MoleculeTopology topology, EnzymeSet set)
        => FindAllSites(sequence, topology, set, null);

    /// <summary>
    /// <see cref="FindAllSites(DnaSequence, MoleculeTopology, EnzymeSet)"/> with methylated bases
    /// blocking recognition (EMBOSS <c>restrict -methylation</c> semantics; see
    /// <see cref="FindSites(DnaSequence, string, MoleculeTopology, IReadOnlyList{Methylase})"/>). The
    /// methylation mask is computed once for the molecule and applied to every enzyme of the set; a
    /// null or empty <paramref name="methylases"/> is the overload without the parameter.
    /// </summary>
    /// <exception cref="ArgumentOutOfRangeException"><paramref name="set"/> is not a defined value.</exception>
    /// <exception cref="ArgumentException">A methylase site is malformed.</exception>
    public static IEnumerable<RestrictionSite> FindAllSites(
        DnaSequence sequence, MoleculeTopology topology, EnzymeSet set, IReadOnlyList<Methylase>? methylases)
    {
        ArgumentNullException.ThrowIfNull(sequence);
        var table = GetEnzymes(set);
        var blocked = MethylationMask.Compute(sequence.Sequence, methylases, topology == MoleculeTopology.Circular);
        return table.Values.SelectMany(e => FindSitesCore(sequence.Sequence, e, topology, blocked));
    }

    /// <summary>
    /// Lists the enzymes of <paramref name="set"/> whose ends can be ligated to an end left by
    /// <paramref name="enzymeName"/> (see <see cref="FindCompatibleEnzymes(string)"/>).
    /// </summary>
    public static IEnumerable<(string Enzyme, string CompatibleEnd)> FindCompatibleEnzymes(
        string enzymeName, EnzymeSet set)
    {
        var query = RequireEnzyme(enzymeName);
        var table = GetEnzymes(set);
        return Enumerate();

        IEnumerable<(string, string)> Enumerate()
        {
            foreach (var candidate in table.Values)
            {
                if (AreCompatible(query, candidate, out string? compatibleEnd))
                    yield return (candidate.Name, compatibleEnd!);
            }
        }
    }

    /// <summary>
    /// Enumerates every unordered pair of distinct enzymes of <paramref name="set"/> whose ends can be
    /// ligated to each other (see <see cref="FindCompatibleEnzymes()"/>, which is this method over
    /// <see cref="EnzymeSet.Common"/>).
    /// </summary>
    /// <remarks>
    /// Lazy, in table order with the first enzyme preceding the second (<c>i &lt; j</c>), so the common set
    /// reproduces <see cref="FindCompatibleEnzymes()"/> exactly. The REBASE set is large — 27 869 of
    /// the 283 881 unordered pairs of its 754 enzymes (9 316 of them blunt-blunt among the defined-overhang
    /// enzymes) — so stream or cap the result rather than materialising it unconditionally.
    /// </remarks>
    /// <exception cref="ArgumentOutOfRangeException"><paramref name="set"/> is not a defined <see cref="EnzymeSet"/> (thrown eagerly).</exception>
    public static IEnumerable<(string Enzyme1, string Enzyme2, string CompatibleEnd)> FindCompatibleEnzymes(
        EnzymeSet set)
    {
        var enzymes = GetEnzymes(set).Values.ToList();
        return Enumerate();

        IEnumerable<(string, string, string)> Enumerate()
        {
            for (int i = 0; i < enzymes.Count; i++)
            {
                for (int j = i + 1; j < enzymes.Count; j++)
                {
                    if (AreCompatible(enzymes[i], enzymes[j], out string? compatibleEnd))
                        yield return (enzymes[i].Name, enzymes[j].Name, compatibleEnd!);
                }
            }
        }
    }

    /// <summary>Isoschizomers of <paramref name="enzymeName"/> within <paramref name="set"/>
    /// (see <see cref="FindIsoschizomers(string)"/>).</summary>
    public static IEnumerable<RestrictionEnzyme> FindIsoschizomers(string enzymeName, EnzymeSet set)
        => SameSiteEnzymes(RequireEnzyme(enzymeName), GetEnzymes(set));

    /// <summary>Equischizomers of <paramref name="enzymeName"/> within <paramref name="set"/>
    /// (see <see cref="FindEquischizomers(string)"/>).</summary>
    public static IEnumerable<RestrictionEnzyme> FindEquischizomers(string enzymeName, EnzymeSet set)
    {
        var query = RequireEnzyme(enzymeName);
        return SameSiteEnzymes(query, GetEnzymes(set)).Where(e => SameCuts(e, query));
    }

    /// <summary>Neoschizomers of <paramref name="enzymeName"/> within <paramref name="set"/>
    /// (see <see cref="FindNeoschizomers(string)"/>).</summary>
    public static IEnumerable<RestrictionEnzyme> FindNeoschizomers(string enzymeName, EnzymeSet set)
    {
        var query = RequireEnzyme(enzymeName);
        return SameSiteEnzymes(query, GetEnzymes(set)).Where(e => !SameCuts(e, query));
    }

    private static bool SameCuts(RestrictionEnzyme a, RestrictionEnzyme b) =>
        a.CutPositionForward == b.CutPositionForward &&
        a.CutPositionReverse == b.CutPositionReverse &&
        a.SecondCut == b.SecondCut;

    private static IReadOnlyDictionary<string, RestrictionEnzyme> LoadRebaseEnzymes()
    {
        var assembly = typeof(RestrictionAnalyzer).Assembly;
        using var stream = assembly.GetManifestResourceStream(RebaseResourceName)
            ?? throw new InvalidOperationException($"Embedded REBASE enzyme table '{RebaseResourceName}' not found.");
        using var reader = new StreamReader(stream);

        var table = new Dictionary<string, RestrictionEnzyme>(StringComparer.OrdinalIgnoreCase);
        string? line;
        while ((line = reader.ReadLine()) is not null)
        {
            if (line.Length == 0 || line[0] == '#')
                continue;

            var f = line.Split('\t');
            if (f.Length != 8)
                throw new InvalidOperationException($"Malformed REBASE enzyme row: '{line}'.");

            string name = f[0];
            // The 39 common enzymes keep their curated instances, so nothing computed with them changes.
            if (_enzymes.TryGetValue(name, out var common))
            {
                table.Add(name, common);
                continue;
            }

            (int, int)? secondCut = f[4].Length == 0 ? null : (Int(f[4]), Int(f[5]));
            table.Add(name, new RestrictionEnzyme(name, f[1], Int(f[2]), Int(f[3]), f[6], f[7])
            {
                SecondCut = secondCut,
            });
        }

        return table;

        static int Int(string s) => int.Parse(s, NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture);
    }

    #endregion
}
