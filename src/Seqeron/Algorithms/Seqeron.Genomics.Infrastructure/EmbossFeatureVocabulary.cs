namespace Seqeron.Genomics.Infrastructure;

/// <summary>
/// The DNA feature vocabulary of EMBOSS 6.6.0 (<c>ajfeat.c</c> <c>featInit</c> / <c>featVocabRead</c> of the <c>emboss</c> vocabulary: <c>Etags.emboss</c> and <c>Efeatures.emboss</c>): the canonical name and the value type of a feature tag
/// (case-insensitive), the type the program prints for a feature key (case-insensitive; aliases, SO ids and GFF3 names map to the EMBL names, an unknown key to <see cref="DefaultType"/>). The tables are generated by
/// <c>scripts/alignment/generate_emboss_feature_vocab.py</c> (A5-8c3b, B09 F218): the tags are read from the installed data files with the include rules of <c>featVocabReadTags</c>, the types are MEASURED on the installed diffseq.
/// </summary>
internal static partial class EmbossFeatureVocabulary
{
    private static readonly Dictionary<string, (string Name, string Kind)> Tags = new(StringComparer.Ordinal);

    private static readonly Dictionary<string, string> Types = new(StringComparer.Ordinal);

    static EmbossFeatureVocabulary()
    {
        foreach (var (key, name, kind) in TagData)
            Tags[key] = (name, kind);
        foreach (var (key, type) in TypeData)
            Types[key] = type;
    }

    /// <summary><c>ajFeattagGetNameS</c> + <c>ajFeattagFormat</c>: the canonical name and the value type of a tag; an unknown tag is <see cref="DefaultTag"/> (<c>known</c> false).</summary>
    internal static (string Name, string Kind, bool Known) Tag(string tag)
    {
        if (Tags.TryGetValue(tag.ToLowerInvariant(), out var t))
            return (t.Name, t.Kind, true);
        var d = Tags[DefaultTag];
        return (d.Name, d.Kind, false);
    }

    /// <summary>The type name the program prints for a feature key ("" for <c>source</c>, which the report of diffseq leaves out).</summary>
    internal static string Type(string key)
        => Types.TryGetValue(key.ToLowerInvariant(), out var t) ? t : DefaultType;
}
