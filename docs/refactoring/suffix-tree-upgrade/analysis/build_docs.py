"""Generate COMPETITOR_MATRIX.md from the TSV evidence files (run from this directory: python3 -I build_docs.py).

Inputs : results/K*.tsv + audit/K0_audit.tsv (+ audit/bench_overrides.tsv, measured cells win),
         func/K*.tsv + audit/K0_func.tsv, FUNCTIONS.md (function names), results/*.meta.tsv (versions, licences).
Output : ../COMPETITOR_MATRIX.md
"""
import csv, glob, re, collections

W = dict(C1=3, C2=2, C3=3, C4=3, C5=2, C6=2, C7=3, C8=2, C9=2, C10=3, C11=3, C12=3, C13=3, C14=2, C15=2, C16=2,
         C17=1, C18=2, C19=2, C20=2, C21=2, C22=1, C23=3, C24=1)
CAPS = list(W)
CAP_NAME = {
    "C1": "Exact search (contains/count/locate/extract)", "C2": "Pattern classes (IUPAC, wildcards)",
    "C3": "Approximate search on the index", "C4": "MEM / MUM / maximal repeats",
    "C5": "Matching statistics / streaming anchors", "C6": "Generalized index (many texts)",
    "C7": "Both strands (reverse complement)", "C8": "Tree / interval navigation API",
    "C9": "Analytics (LRS, distinct substrings, k-mer stats)", "C10": "Construction speed",
    "C11": "Index memory", "C12": "Query speed", "C13": "Scale (> 2^32 chars)",
    "C14": "External / larger-than-RAM", "C15": "Parallel construction", "C16": "Concurrent queries",
    "C17": "Online / dynamic updates", "C18": "Compression (succinct index)",
    "C19": "Alphabet generality + 2-bit DNA", "C20": "Persistence (format, mmap, version, integrity)",
    "C21": ".NET API quality & integration", "C22": "Distribution & exposure", "C23": "Verification",
    "C24": "Maintenance & licence"}
NAMES = {"K0": "Seqeron", "K1": "sdsl", "K2": "SeqAn3", "K3": "GenomeTools", "K4": "MUMmer4", "K5": "libsais",
         "K6": "Go", "K7": "rust-bio", "K8": "Python", "K9": ".NET", "K10": "BWA/Bt2", "K11": "r-index",
         "K12": "ropebwt3"}
IDS = list(NAMES)
F = [f"F{i:02d}" for i in range(1, 82)]
GROUPS = [("A Construction & structure variants", F[0:11]), ("B Exact search", F[11:24]),
          ("C Pattern types", F[24:30]), ("D Approximate search", F[30:35]),
          ("E Matching & comparison between texts", F[35:44]), ("F Repeats & text statistics", F[44:53]),
          ("G Tree / interval navigation", F[53:65]), ("H Persistence, interoperability, operations", F[65:75]),
          ("I Alphabets", F[75:81])]


def rows(path):
    with open(path, encoding="utf-8") as f:
        rd = csv.reader(f, delimiter="\t")
        next(rd)
        yield from rd


cap = collections.defaultdict(dict)   # cap[k][c] = (score, flag)
for p in glob.glob("results/K*.tsv") + ["audit/K0_audit.tsv", "audit/bench_overrides.tsv"]:
    if p.endswith(("meta.tsv", "survey.tsv")):
        continue
    for r in rows(p):
        cap[r[0]][r[1]] = (int(r[2]), r[3])

fn = collections.defaultdict(dict)    # fn[k][f] = (score, flag, evidence)
for p in glob.glob("func/K*.tsv") + ["audit/K0_func.tsv"]:
    if p.endswith(".extra.tsv"):
        continue
    for r in rows(p):
        fn[r[0]][r[1]] = (int(r[2]), r[3], r[4])

fname = {}
for line in open("FUNCTIONS.md", encoding="utf-8"):
    m = re.match(r"(F\d\d) (.*)", line.strip())
    if m:
        fname[m.group(1)] = m.group(2)

meta = {}
for p in glob.glob("results/*.meta.tsv"):
    for r in rows(p):
        meta[r[0]] = r


def cmean(k):
    return sum(cap[k][c][0] * W[c] for c in CAPS) / sum(W.values())


def fcov(k, tree_only=False):
    s = 0
    for f in F:
        v, _, ev = fn[k][f]
        if tree_only and k == "K0" and ev.startswith("Genomics:"):
            v = 0
        s += v
    return s / 162


out = []
w = out.append
w("# Suffix-tree competitor matrices (2026-11-03)\n")
w("Generated by `analysis/build_docs.py` from the evidence files in `analysis/results`, `analysis/func`, `analysis/audit`. "
  "Every cell has a source URL (or a repo path:line for Seqeron) in those TSV files; this page only shows the scores.\n")
w("Scales: **properties** 0-4 (4 = best in class / within 1.5x of the best measured tool), flag `V` verified in the primary "
  "source or measured here, `U` unverified and scored optimistically for the competitor. **Functions** 0 absent, 1 partial / "
  "workaround, 2 full (documented, directly callable). Rubrics: `analysis/SPEC.md`, `analysis/FUNCTIONS.md`. "
  "Cells C10-C13, C15, C16 of Seqeron and C10-C12 of K1, K5-K8, K10 are overridden by measurements "
  "(`analysis/audit/bench_overrides.tsv`, `BENCHMARK.md`).\n")

w("## 1. Competitors\n")
w("| id | tool | version scored | licence |\n|---|---|---|---|")
for k in IDS[1:]:
    m = meta.get(k)
    ver = m[2] if m else ""
    lic = m[4] if m else ""
    w(f"| {k} | {m[1] if m else NAMES[k]} | {ver} | {lic} |")
w("| K0 | Seqeron.SuffixTree (this repository, commit 24231842) | 1.0.0 | repository licence |\n")
w("Not scored (scouting list, `analysis/results/scout.md`): Movi 2, Move-r / Move-rb (arXiv id unverified), Columba / b-move, "
  "suffixient arrays, grlBWT, sr-index, copMEM2, gsufsort, GBWT/GCSA2, SBWT / Themisto / Fulgor / Metagraph.\n")

w("## 2. Ranking\n")
w("| rank | tool | property mean (weighted, 0-4) | function coverage (81 functions) |\n|---|---|---|---|")
for i, k in enumerate(sorted(IDS, key=lambda k: -cmean(k)), 1):
    mark = " **(this project)**" if k == "K0" else ""
    w(f"| {i} | {NAMES[k]}{mark} | {cmean(k):.2f} | {fcov(k) * 100:.1f}% |")
w("")
w(f"Seqeron function coverage counts functions that live in the wider Seqeron.Genomics library (motif scans, approximate "
  f"matching, repeat finders) as 1-2. **Suffix-tree layer only** (those rows set to 0): {fcov('K0', True) * 100:.1f}%. "
  f"The best competitor, sdsl, is {max(fcov(k) for k in IDS[1:]) * 100:.1f}%. The functional lead is therefore thin and "
  f"depends on how the library boundary is drawn.\n")
u_cap = sum(1 for k in IDS[1:] for c in CAPS if cap[k][c][1] == "U")
u_fn = sum(1 for k in IDS[1:] for f in F if fn[k][f][1] == "U")
w(f"Unverified (`U`) cells among competitors: {u_cap} of {24 * 12} property cells, {u_fn} of {81 * 12} function cells. "
  f"Each was scored optimistically, so a competitor's real score can only be lower.\n")

w("## 3. Table B - properties (24 x 13)\n")
w("| cap | property | w | " + " | ".join(NAMES[k] for k in IDS) + " |")
w("|---|---|---|" + "---|" * len(IDS))
for c in CAPS:
    w(f"| {c} | {CAP_NAME[c]} | {W[c]} | " + " | ".join(f"{cap[k][c][0]}{cap[k][c][1].lower()}" for k in IDS) + " |")
w("| | **weighted mean** | | " + " | ".join(f"**{cmean(k):.2f}**" for k in IDS) + " |\n")
w("`v` verified, `u` unverified (optimistic for the competitor).\n")

w("## 4. Table A - functions (81 x 13)\n")
hdr = "| id | function | " + " | ".join(NAMES[k] for k in IDS) + " |"
sep = "|---|---|" + "---|" * len(IDS)
for g, fs in GROUPS:
    w(f"### {g}\n")
    w(hdr)
    w(sep)
    for f in fs:
        w(f"| {f} | {fname[f]} | " + " | ".join(str(fn[k][f][0]) for k in IDS) + " |")
    w("| | **group coverage** | " + " | ".join(
        f"**{sum(fn[k][f][0] for f in fs) / (2 * len(fs)) * 100:.0f}%**" for k in IDS) + " |\n")
w("| | **TOTAL coverage** | " + " | ".join(f"**{fcov(k) * 100:.1f}%**" for k in IDS) + " |\n")

w("## 5. Where Seqeron is behind or ahead (functions)\n")
gaps = []
for f in F:
    s = fn["K0"][f][0]
    others = {k: fn[k][f][0] for k in IDS[1:]}
    best = max(others.values())
    if best > s:
        gaps.append((best - s, sum(1 for v in others.values() if v == 2), f, s, best))
gaps.sort(key=lambda r: (-r[0], -r[1]))
w(f"Seqeron scores below the best competitor on **{len(gaps)} of 81** functions. Largest first (n2 = how many competitors "
  f"score 2):\n")
w("| id | function | Seqeron | best | n2 |\n|---|---|---|---|---|")
for gap, n2, f, s, b in gaps:
    w(f"| {f} | {fname[f]} | {s} | {b} | {n2} |")
ahead = [f for f in F if fn["K0"][f][0] > max(fn[k][f][0] for k in IDS[1:])]
w(f"\nSeqeron scores above every competitor on: {', '.join(f'{f} ({fname[f]})' for f in ahead)}.\n")

w("## 6. Evidence\n")
w("Per-cell evidence (sentence, URL, access date, V/U flag): `analysis/results/*.tsv` (properties), `analysis/func/*.tsv` "
  "(functions), `analysis/audit/K0_audit.tsv` and `analysis/audit/K0_func.tsv` (Seqeron, with `path:line` in the repo), "
  "`analysis/audit/bench_overrides.tsv` (measured cells). Functions of competitors that fit none of F01-F81 are listed in "
  "`analysis/func/*.extra.tsv`. Seqeron's own hard limits and defects found by the audit: `analysis/audit/K0_gaps.md`.\n")

with open("../COMPETITOR_MATRIX.md", "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out) + "\n")
print("written ../COMPETITOR_MATRIX.md", len(out), "lines")
print("tree-only coverage", round(fcov("K0", True) * 100, 1), "whole library", round(fcov("K0") * 100, 1))
print("U cells", u_cap, u_fn)
